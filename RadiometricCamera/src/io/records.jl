"""The file beside a directory's grid cameras that holds their initialization region ([`save_initialization_region`](@ref))."""
const INITIALIZATION_REGION_FILE = "initialization_region.json"

"""
    save_initialization_region(dir, region)

The initialization region `region` (any of Core's regions, in pixels: a `Rect2`, an `Ellipse`, a `Circle`, their `RegionIntersection`
or the `WholePlane`) of the grid cameras the pipeline writes in `dir` — the start's, where every one of them is defined as a start — as
`dir/initialization_region.json`, an `rc/initialization_region/v1.0` record (IO 0.10's region body). Written beside every grid the
pipeline writes (the saved initialization, the checkpoints, the result), so each is a valid start ([`load_start`](@ref)).
"""
function save_initialization_region(dir::AbstractString, region)
    s = _style(VgtkCore.m)
    VgtkIO.write_record(joinpath(dir, INITIALIZATION_REGION_FILE),
                        (; schema = RECORD_SCHEMAS.initialization_region, initialization_region = JSON.lower(s, region, (; region = true))); style = s)
    return nothing
end

"""
    stored_initialization_region(grid_path) -> region

The initialization region of the grid camera record `grid_path`: the `rc/initialization_region/v1.0` record beside it
(`initialization_region.json`, [`save_initialization_region`](@ref)), any of Core's regions. A grid without one (a run from a
parametric start, defined by its own valid domain, records none) is an `ArgumentError` — a stored grid start never falls back to the
whole sensor.
"""
function stored_initialization_region(grid_path::AbstractString)
    f = joinpath(dirname(grid_path), INITIALIZATION_REGION_FILE)
    if !isfile(f)
        again = _regenerate_hint(grid_path, "re-run the start that wrote it (its options' bin/refine.jl --stage=start)")
        throw(ArgumentError("$grid_path: no $INITIALIZATION_REGION_FILE beside it — a stored grid start is defined only on its run's " *
                            "initialization region (rc/initialization_region/v1.0), never the sensor by default; a grid of an earlier run " *
                            "(RC ≤ 0.9.0-dev, the region in its parameters.json) is regenerated: $again; a run from a parametric start " *
                            "records none"))
    end
    r, s = _read_kind(f, :initialization_region)
    return JSON.lift(s, Union{VgtkCore.Rect2, VgtkCore.Ellipse, VgtkCore.Circle, VgtkCore.RegionIntersection, VgtkCore.WholePlane}, r.initialization_region)
end

"""
    save_image_region(path, m; provenance = (;))

The measured image region `m` of a capture set ([`measure_image_region`](@ref)'s result) as an `rc/image_region/v1.0` record
(IO's `write_record`): `lens_coverage` the region (IO's region body, a leaf: the measured `Ellipse`, COLMAP pixels of the raw grid),
`extent` the photographs' `[W, H]`, `frames` the photographs it was measured on and the detector's diagnostics (`center_scale`,
`axes_scale` px, `inliers` of `candidates` rim candidates, the largest `rim_gap` rad, `cut` by the frame). Read by
[`load_image_region`](@ref) — every consumer's one reader (a run's `camera.lens_coverage`).
"""
function save_image_region(path::AbstractString, m; provenance::NamedTuple = (;))
    s = _style(VgtkCore.m)
    body = (; schema = RECORD_SCHEMAS.image_region, lens_coverage = JSON.lower(s, m.lens_coverage, (; region = true)),
            extent = collect(Int.(m.extent)), frames = collect(String.(m.frames)), center_scale = collect(Float64.(m.center_scale)),
            axes_scale = collect(Float64.(m.axes_scale)), inliers = Int(m.inliers), candidates = Int(m.candidates),
            rim_gap = Float64(m.rim_gap), cut = Bool(m.cut))
    VgtkIO.write_record(path, VgtkIO.with_provenance(body, provenance); style = s)
    return path
end

"""
    load_image_region(path) -> (; lens_coverage, extent, frames, record)

The `rc/image_region/v1.0` record `path` ([`save_image_region`](@ref)): its measured lens coverage (an `Ellipse` or a `Circle`,
COLMAP pixels), the photographs' `(W, H)`, the frames it was measured on, and the record as read. Another schema is an
`ArgumentError` naming it.
"""
function load_image_region(path::AbstractString)
    r, s = _read_kind(path, :image_region)
    c = JSON.lift(s, Union{VgtkCore.Ellipse, VgtkCore.Circle}, r.lens_coverage)
    return (; lens_coverage = c, extent = (Int(r.extent[1]), Int(r.extent[2])), frames = String[String(f) for f in r.frames], record = r)
end

# ---- the calibration state -----------------------------------------------------------------------------------------------------
_settings_body(st::RenderSettings) = (
    sensor = (nodes = isqrt(length(st.sensor)),),
    aperture = (radial_nodes = n_disc(st.aperture) ÷ n_border(st.aperture), angular_nodes = n_border(st.aperture)),
    sampler = (samples = st.sampler.N, seed = Int(st.sampler.seed), hammersley = st.sampler.hammersley),
)
_settings_from_body(b) = RenderSettings(; n_𝐩 = Int(b.sensor.nodes), n_ρ = Int(b.aperture.radial_nodes), n_φ = Int(b.aperture.angular_nodes),
                                        N = Int(b.sampler.samples), seed = Int(b.sampler.seed), hammersley = b.sampler.hammersley::Bool)

# The poses of the photographs (camera → world, plain metres) as Core's trajectory of the camera into the world, named by the photographs.
_poses_trajectory(poses, names) = VgtkCore.Trajectory(VgtkCore.ViewFrame{:cam}, VgtkCore.WorldFrame,
    Dict(k => VgtkCore.with_unit(_pose_eltype(Float64, poses[k]), VgtkCore.m) for k in eachindex(poses));
    images = Dict(k => String(names[k]) for k in eachindex(names)))

"""
    save_state(path, s::CalibrationState, names; page_flip = nothing, provenance = (;))
    save_state(path, state::NamedTuple; length_unit = mm, provenance = (;))

A refinement's state as an `rc/calibration_state/v3.1` record (VisualGeometryToolkitIO's file boundary; `records.jl`'s header): the
radiometric camera, the radiometric target, the poses of the photographs (`names`, in order) as IO's trajectory body, the light as VisualRadiometryToolkitIO's
environment light body, the render settings, the photographs' observation model (`observation_model(s)`) and the page's ±y choice
(`page_flip`, the Schöps front end's; omitted when `nothing`). `state` holds the fields [`load_state`](@ref) returns (`camera, target,
poses, names, light, settings, observation, page_flip`). A run's labels (the iteration, the costs) go in `provenance`.
"""
save_state(path::AbstractString, s::CalibrationState, names; page_flip = nothing, provenance::NamedTuple = (;)) =
    save_state(path, (; camera = s.camera, target = radiometric_target(s), poses = s.poses, names, light = s.light, settings = s.settings,
                        observation = observation_model(s), page_flip); provenance)
function save_state(path::AbstractString, st::NamedTuple; length_unit = VgtkCore.mm, provenance::NamedTuple = (;))
    s = _style(length_unit)
    body = merge((schema = RECORD_SCHEMAS.calibration_state,),
                 (camera = _camera_body(s, st.camera), target = st.target, poses = _poses_trajectory(st.poses, st.names), light = _with_metres(st.light),
                  settings = _settings_body(st.settings), observation_model = st.observation::ObservationModel),
                 st.page_flip === nothing ? (;) : (page_flip = Float64(st.page_flip),))
    VgtkIO.write_record(path, VgtkIO.with_provenance(body, provenance); style = s)
    return nothing
end

"""
    load_state(path) -> NamedTuple

The state of a refinement's state file (`state.json`, `state_it<N>.json`, a start record's state.json; `rc/calibration_state/v3.1`,
[`save_state`](@ref)): `(; camera, target, poses, names, light, settings, observation, page_flip)` — the `RadiometricCameraModel`, the
[`RadiometricTarget`](@ref) (`board_surface(board, target)` the scene's surface on a board of its page's aspect), the poses (camera → world, plain metres) of the
photographs `names`, Core's `EnvironmentLight` (plain metres), the [`RenderSettings`](@ref), the photographs' [`ObservationModel`](@ref)
and the ±y choice (`nothing` when the state records none); `calibrated_camera(load_state(path))` its [`CalibratedCamera`](@ref). A
v3.0 state (RC 0.9–0.11.0) states no observation model and is refused by name with the step that regenerates it.
"""
function load_state(path::AbstractString)
    r, s = _read_kind(path, :calibration_state)
    _check_pixel_frame(path, r)
    camera = _camera_from_body(s, r.camera)
    tr = JSON.lift(s, VgtkCore.Trajectory, r.poses)
    ks = sort!(collect(keys(tr)))
    poses = [_pose_eltype(Float64, VgtkCore.ustrip(VgtkCore.m, tr[k])) for k in ks]   # unlabelled, plain metres
    return (; camera, target = JSON.lift(s, RadiometricTarget, r.target), poses, names = [tr.images[k] for k in ks],
              light = VgtkCore.ustrip(VgtkCore.m, JSON.lift(s, VrtkCore.EnvironmentLight, r.light)), settings = _settings_from_body(r.settings),
              observation = JSON.lift(s, ObservationModel, r.observation_model),
              page_flip = haskey(r, :page_flip) ? Float64(r.page_flip::Real) : nothing)
end
