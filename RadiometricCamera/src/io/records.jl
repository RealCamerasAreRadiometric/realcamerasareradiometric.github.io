# ---------------------------------------------------------------------------
# RadiometricCamera's records — its kinds, each read and written through VisualGeometryToolkitIO (`write_record`, `read_record`): every
# Core value in them is IO's own record of it, lowered and lifted on IO's `VgioStyle`, and RC's types are lowered and lifted on that
# style too (the methods are RC's: it owns the types).
#
#   rc/radiometric_camera/v3.1   a CalibratedCamera         {<IO's envelope>, <camera body>, "observation_model", "settings"}
#   rc/radiometric_target/v2.0   a RadiometricTarget        {<IO's envelope>, <target body>}
#   rc/run_parameters/v3.0       a refinement's run         {<IO's envelope; units.length "m">, <what the run was given and measured>}
#   rc/initialization_region/v1.0  the grids' start region  {<IO's envelope>, "initialization_region" IO's region body} (initialization_region.json)
#   rc/calibration_state/v3.1    a refinement's state       {<IO's envelope>, "camera", "target", "poses", "light", "settings", "observation_model"[, "page_flip"]}
#
# IO's envelope (VisualGeometryToolkitIO 0.10, `write_record(path, record; style)`): the `schema`, the `generator`, ONE `units` object
# (`length` the record's length unit, `pixel` "colmap": RC's models are in COLMAP pixels) and ONE `conventions` object, then the body,
# then the `provenance`; the body states no unit of its own. `VgioStyle(record)` is the style a record's `units` declare. A record of an
# earlier RC version (rc/radiometric_camera/v1–v2, rc/radiometric_target/v1, rc/run_parameters/v1, rc/calibration_state/v1–v2: RC ≤
# 0.8, on IO 0.9's envelope) is refused by name: a derived result, regenerated by the run that made it. So is a camera or a state of
# RC 0.9–0.11.0 (rc/radiometric_camera/v3.0, rc/calibration_state/v3.0): it states no observation model, the sensor characterisation
# and the photograph kind a prediction must read its photographs under (owner 2026-11-15: "refuse old keys; we must get up to date";
# RC 0.11.1 retired the v1/v2 state's version step, ruling (A'), with them).
#
# The camera body: "camera" IO's bounded camera body (`camera_json(::BoundedCamera, frame; length_unit)`: the model's body — K in
# COLMAP pixels and the lens record — the extent, the sensor's pitch and the lens coverage), "aperture" {"radius"} (a length),
# "focus" the focus surface as a parametric record {"type", "nodes", "parameters", "unit": "1/m"} (the nodal inverse distances t̂ᵢ;
# its type "sensor_thin_plate_spline", its nodes COLMAP pixels), "vignetting" VisualRadiometryToolkitIO's vignetting body (a camera without vignetting has none: saving it is refused there); a camera record also
# "observation_model" and "settings" (a CalibratedCamera: below).
# The observation model (observation_model.jl): {"sensor": {"type": "record", "sha256": <the characterisation file's sha256>} |
# {"type": "none"}, "photos": {"kind": "photosites", "channel": "R" | "G" | "B"} | {"kind": "decoded", "channel": "RGB" | "R" | "G" | "B",
# "srgb": <bool>}}.
# The target body: ["target" IO's target body,] "warping" (the HEIGHT_NC nodal heights, lengths), "warping_aspect" (the height / width
# of the page the warping was learned on; required unless every nodal height is zero, a flat warping, which fits any page),
# ["inplane_print_error" the in-plane print error as IO's target-calibration record (rig_schema.jl): {"type": "composition", "compose":
# [{"type": "aspect", "parameters": [a]}, {"type": "skew", "parameters": [u]}]}, Core's Aspect ∘ Skew in the warping's placed chart;
# absent = the design as printed,] "material" {"alpha_ink",
# "alpha_noink", "eta_ink": [R, G, B], "eta_noink": [R, G, B], "mu"} (every one dimensionless: the GGX roughnesses α, the refractive
# indices η per channel, the diffuse weight μ ∈ [0, 1]; IO's file-level declaration has no dimensionless form to state it in, the IO
# units wave's), "ink_spread" (a length) and "print_blur" IO's blur block (a
# blur on the print: its covariance a length²).
# The state: "poses" IO's trajectory body (camera → world, `view:cam` → `world`, the photographs' names as its images), "light" VisualRadiometryToolkitIO's
# environment light body, "settings" the render settings' constructor arguments ({"sensor": {"nodes"}, "aperture":
# {"radial_nodes", "angular_nodes"}, "sampler": {"samples", "seed", "hammersley"}}), "observation_model" its photographs', "page_flip"
# the Schöps front end's ±y choice of the page rows. Lengths in the `units` object's `length` through
# IO's decimal-exact `write_length` / `read_length`; a pose as IO's minimal form (a quaternion and a translation).
# ---------------------------------------------------------------------------

"""The schema of each RadiometricCamera kind, by its name: the version this package writes and reads (IO 0.10's envelope). An
earlier version (RC ≤ 0.8: IO 0.9's envelope) is refused by name: regenerate it."""
const RECORD_SCHEMAS = (radiometric_camera = "rc/radiometric_camera/v3.1", radiometric_target = "rc/radiometric_target/v2.0",
                        calibration_state = "rc/calibration_state/v3.1", run_parameters = "rc/run_parameters/v3.0",
                        # the initialization region of the grid cameras in a directory (initialization_region.json): their start's region
                        initialization_region = "rc/initialization_region/v1.0",
                        # the run's reports (IO 0.10's `write_record` states every file's schema): the self-check's summary and per-view
                        # vectors (selfcheck.json, selfcheck_vectors.json)
                        selfcheck = "rc/selfcheck/v1.0", selfcheck_vectors = "rc/selfcheck_vectors/v1.0",
                        # the start of a refinement (start.json of a start record: start/start_record.jl)
                        refinement_start = "rc/refinement_start/v1.0",
                        # the measured image region of a capture set (its keyed step: start/image_region.jl; camera.lens_coverage)
                        image_region = "rc/image_region/v1.0")

const _COLMAP = VgtkCore.PixelFrame{:colmap}       # the pixel frame RC's models are in (frames rule 1); every record declares it
# The style of an RC record with lengths in `u`: its `units` object (IO's envelope) declares `u` and the COLMAP pixel frame.
_style(u) = VgtkIO.VgioStyle(; length_unit = u, pixel_frame = _COLMAP)
# The focus surface's type in a record: the thin plate spline over the sensor (its nodes COLMAP pixels). The types of the removed
# focus surfaces on the chief directions are refused by name (`_focus_from_body`).
const FOCUS_TYPE = "sensor_thin_plate_spline"
const REMOVED_FOCUS_TYPES = ("direction_thin_plate_spline", "direction_spherical_spline")

_len(x, u) = VgtkIO.write_length(x * VgtkCore.m, u)                  # a plain metre value → the file's number
_floats(v) = Float64[Float64(x::Real) for x in v]
# A value with lengths as IO's records hold it (quantities): RC's plain values are in metres (a light, a scene's target).
_with_metres(x) = VgtkCore.has_units(x) ? x : VgtkCore.with_unit(x, VgtkCore.m)

# ---- the radiometric camera ----------------------------------------------------------------------------------------------------
# The camera body: IO's BOUNDED camera body (`camera_json(camera::BoundedCamera, frame; length_unit)`, camera_schema.jl, the body a
# camera store's entry and a rig sensor embed): the model's body (K in COLMAP pixels,
# the lens record, a SplineLens's `{"spline": …}` too), the extent, the sensor's `pitch` when the camera is bounded by a physical `Sensor` and its `lens_coverage` (the image
# circle) when the lens does not cover the whole sensor. Read back by `camera_from_json(BoundedCamera, body, frame; length_unit)`.
_aperture_body(u, c) = (radius = _len(c.aperture_radius, u),)

"""The lens of a camera body (IO's bounded body: its pitch and lens coverage too). A non-central body — the record of the removed
non-central model, its aperture body holding a `radius_grid` — is refused by name: every camera is central."""
function _lens_from_body(s, b, aperture)
    haskey(aperture, :radius_grid) && throw(ArgumentError(
        "the record holds a non-central camera (its aperture has a `radius_grid`): the non-central spline model is removed, every camera " *
        "is central; regenerate the record from a central start"))
    return VgtkIO.camera_from_json(VgtkCore.BoundedCamera, b, _COLMAP; length_unit = s.length_unit)
end

_focus_body(f::Focus) = (type = FOCUS_TYPE, nodes = [Float64[n[1], n[2]] for n in f.nodes], parameters = Float64.(collect(f.t̂_i)),
                         unit = "1/m")
function _focus_from_body(b)
    type = b.type::String
    type in REMOVED_FOCUS_TYPES && throw(ArgumentError(
        "focus: the focus surface type $(repr(type)) was removed (the focus A/B experiment is decided: the focus surfaces on the " *
        "chief directions are deleted); the one focus surface is $(repr(FOCUS_TYPE)), the sensor-grid thin plate spline — " *
        "refine again from the run's start with the current package"))
    type == FOCUS_TYPE || throw(ArgumentError("focus: $(repr(type)) is not a focus surface type (the one type: $(repr(FOCUS_TYPE)))"))
    b.unit == "1/m" || throw(ArgumentError("focus: the inverse distances are in 1/m (got $(repr(b.unit)))"))
    return Focus(FocusSpline([SVector{2, Float64}(_floats(n)...) for n in b.nodes::Vector{Any}]), _floats(b.parameters))
end

# (RC's own functions, not methods of JSON.lower / JSON.lift: the camera type is VisualRadiometryToolkitCore's and the style IO's — a
# method here would be type piracy; the kind `rc/radiometric_camera` is RC's)
_camera_body(s::VgtkIO.VgioStyle, c::RadiometricCameraModel) = (
    camera = VgtkIO.camera_json(c.geometric, _COLMAP; length_unit = s.length_unit), aperture = _aperture_body(s.length_unit, c), focus = _focus_body(c.focus),
    vignetting = c.vignetting,
)
# A blur block's PLANE (IO 0.10's blur body names it; its covariance's frame in memory): the print's blur is on the board's printed
# plane, `PRINT_PLANE` (a length², the record's `units.length`²). RC holds it unlabeled in memory (one board): the plane is stated at
# the record's boundary and checked on read, so a block of another plane never lifts into it.
"""The plane a radiometric target's print blur is recorded on: the printed board's (`TargetPlaneFrame{:board}`; RC's one target)."""
const PRINT_PLANE = VgtkCore.TargetPlaneFrame{:board}
_plane(::VgtkCore.CovMat{N, T, M, F}) where {N, T, M, F} = F
_on_plane(::Type{F}, b::VgtkCore.GaussianBlur) where {F} = VgtkCore.GaussianBlur(VgtkCore.relabel(F, cov(b)))
_unlabeled(b::VgtkCore.GaussianBlur) = _on_plane(VgtkCore.UnlabeledFrame{2}, b)
_plane_name(F) = F <: VgtkCore.PixelFrame ? "the pixel frame $(VgtkIO.pixel_frame_name(F))" : string(nameof(F), F isa DataType && !isempty(F.parameters) ? "{$(repr(F.parameters[1]))}" : "")
function _print_blur(s, b)
    blur = JSON.lift(s, VgtkCore.GaussianBlur, b)
    _plane(cov(blur)) === PRINT_PLANE ||
        throw(ArgumentError("print_blur: a blur on the print is on the board's plane (\"frame\": \"target:board\"), got $(_plane_name(_plane(cov(blur))))"))
    return _unlabeled(blur)
end
function _check_pixel_frame(path, r)
    r.units.pixel == VgtkIO.pixel_frame_name(_COLMAP) ||
        throw(ArgumentError("$path: RadiometricCamera's models are in COLMAP pixels, the record states the pixel frame $(repr(r.units.pixel))"))
    return r
end

function _camera_from_body(s::VgtkIO.VgioStyle, r)
    lens = _lens_from_body(s, r.camera, r.aperture)
    return RadiometricCameraModel(lens, _focus_from_body(r.focus), VgtkIO.metres(r.aperture.radius, s.length_unit),
                                  JSON.lift(s, AbstractVignetting, r.vignetting))
end

# ---- the observation model and the calibrated camera ------------------------------------------------------------------------------
_sensor_statement_body(::NoSensorRecord) = (type = "none",)
_sensor_statement_body(r::SensorRecord) = (type = "record", sha256 = r.sha256)
_photos_body(::Photosites, channel::Symbol) = (kind = "photosites", channel = string(channel))
_photos_body(k::Decoded, channel::Symbol) = (kind = "decoded", channel = string(channel), srgb = k.srgb)
JSON.lower(::VgtkIO.VgioStyle, o::ObservationModel) = (sensor = _sensor_statement_body(o.sensor), photos = _photos_body(o.kind, o.channel))
function _sensor_statement_from_body(b)
    b.type == "none" && return NoSensorRecord()
    b.type == "record" && return SensorRecord(b.sha256::String)
    throw(ArgumentError("observation_model.sensor: $(repr(b.type)) is neither \"record\" nor \"none\""))
end
function _kind_from_body(b)
    b.kind == "photosites" && return Photosites()
    b.kind == "decoded" && return Decoded(b.srgb::Bool)
    throw(ArgumentError("observation_model.photos: $(repr(b.kind)) is neither \"photosites\" nor \"decoded\""))
end
JSON.lift(::VgtkIO.VgioStyle, ::Type{ObservationModel}, b) =
    ObservationModel(_sensor_statement_from_body(b.sensor), _kind_from_body(b.photos), Symbol(b.photos.channel::String))
JSON.lower(s::VgtkIO.VgioStyle, c::CalibratedCamera) =
    merge(_camera_body(s, c.model), (observation_model = c.observation, settings = _settings_body(c.settings)))
JSON.lift(s::VgtkIO.VgioStyle, ::Type{CalibratedCamera}, r) =
    CalibratedCamera(_camera_from_body(s, r), JSON.lift(s, ObservationModel, r.observation_model), _settings_from_body(r.settings))

# ---- the radiometric target ----------------------------------------------------------------------------------------------------
_material_body(m::Material) = (alpha_ink = Float64(m.roughness_ink), alpha_noink = Float64(m.roughness_paper), eta_ink = Float64.(collect(m.refractive_index_ink)),
                               eta_noink = Float64.(collect(m.refractive_index_paper)), mu = Float64(m.diffuse_weight))
_material_from_body(b) = Material(Float64(b.alpha_ink::Real), Float64(b.alpha_noink::Real), _floats(b.eta_ink), _floats(b.eta_noink), Float64(b.mu::Real))

function JSON.lower(s::VgtkIO.VgioStyle, t::RadiometricTarget)
    u = s.length_unit; r = t.radiometry
    return merge(t.target === nothing ? (;) : (target = _with_metres(t.target),),
                 (warping = [_len(h, u) for h in t.warping],),
                 t.aspect === nothing ? (;) : (warping_aspect = t.aspect,),
                 iszero(t.inplane) ? (;) : (inplane_print_error = _inplane_body(s, t.inplane),),
                 (material = _material_body(r.material), ink_spread = VgtkIO.write_length(r.ink_spread, u),
                  print_blur = _on_plane(PRINT_PLANE, r.print_blur)))   # IO's blur block on the board's plane, lengths² in u²
end
function JSON.lift(s::VgtkIO.VgioStyle, ::Type{RadiometricTarget}, b)
    u = s.length_unit
    target = haskey(b, :target) ? JSON.lift(s, VgtkCore.AbstractTarget, b.target) : nothing
    rad = TargetRadiometry(_material_from_body(b.material), VgtkIO.read_length(b.ink_spread::Real, u),
                           _print_blur(s, b.print_blur))   # (on the board's plane: m² quantities back)
    h = SVector{HEIGHT_NC}(Float64[VgtkIO.metres(x, u) for x in b.warping::Vector{Any}])
    aspect = haskey(b, :warping_aspect) ? Float64(b.warping_aspect::Real) : nothing   # (a warped target without one: an ArgumentError)
    inplane = haskey(b, :inplane_print_error) ? _inplane_from_body(s, b.inplane_print_error) : zero(SVector{INPLANE_NC, Float64})
    return RadiometricTarget(target, h, aspect, rad; inplane)
end
# The in-plane print error as IO's target-calibration record (rig_schema.jl), written and read by IO's own writer and reader of a
# target calibration (`target_calibration_json` / `target_calibration_from_json`, public since IO 0.9.5: the bodies a target's `calibration` embeds): the
# composition of Core's Aspect ∘ Skew (`inplane_calibration`), its members listed outer first by their tag and parameter vector.
# Read back, anything but Aspect ∘ Skew (another kind, order or count) is an ArgumentError.
_inplane_body(s, θ::SVector{INPLANE_NC}) = VgtkIO.target_calibration_json(s, inplane_calibration(θ))
function _inplane_from_body(s, b)
    c = VgtkIO.target_calibration_from_json(s, b)
    c isa ComposedTransformation{<:VgtkCore.Aspect, <:VgtkCore.Skew} ||
        throw(ArgumentError("inplane_print_error: the in-plane print error is the composition aspect ∘ skew (Core's Aspect ∘ Skew), got $(typeof(c))"))
    return SVector{INPLANE_NC, Float64}(only(VgtkCore.parameter_vector(c.t1)), only(VgtkCore.parameter_vector(c.t2)))
end

# ---- files --------------------------------------------------------------------------------------------------------------------
# The options of the run that wrote `path`: bin/refine.jl writes them as `<io.out>/pipeline_config.toml` with `io.out` absolute
# (`write_pipeline_config`), so the file beside `path` is that run's only when its own `io.out` IS `path`'s directory (the same
# directory by `samefile`: a symlink, a trailing `/`) — in a shared directory (a saved initialization's) it is another run's. A file
# that is not such a record (unparsable, `io` not a table, a relative `io.out`: its writer's directory is unknown) names nothing.
# Returns the options file, or `nothing`.
function _writer_config(path::AbstractString)
    dir = dirname(abspath(path))
    cfg = joinpath(dir, PIPELINE_CONFIG_FILE)
    isfile(cfg) || return nothing
    t = TOML.tryparsefile(cfg)
    t isa AbstractDict || return nothing
    io = get(t, "io", nothing)
    io isa AbstractDict || return nothing
    out = get(io, "out", nothing)
    return out isa AbstractString && isabspath(out) && samefile(out, dir) ? cfg : nothing
end
# The regeneration of the record `path` (an earlier run's): the bin/refine.jl run of its writer's options when they are known
# (`_writer_config`), else what to look for.
_regenerate_hint(path::AbstractString, otherwise::AbstractString) =
    (cfg = _writer_config(path)) === nothing ? otherwise : "re-run that refinement (`julia --project=. bin/refine.jl --config=$cfg`)"

# Why an earlier version of a kind is refused, beyond RC ≤ 0.8's envelope: a camera or a state of RC 0.9–0.11.0 states no observation model.
const _NO_OBSERVATION_MODEL = "written by RC 0.9–0.11.0, it states no observation model (the sensor characterisation its photographs " *
                              "were read under and their kind), which every prediction of the camera must read its photographs under"
_refused_because(schema) = schema in ("rc/radiometric_camera/v3.0", "rc/calibration_state/v3.0") ? _NO_OBSERVATION_MODEL : "written by RC ≤ 0.8 on IO 0.9"
function _read_kind(path::AbstractString, kind::Symbol)
    r = VgtkIO.read_record(path)
    schema = get(r, :schema, nothing)
    current = RECORD_SCHEMAS[kind]
    if schema != current
        old = schema isa AbstractString && startswith(schema, first(rsplit(current, '/'; limit = 2)) * "/")
        throw(ArgumentError("$path: not a $current record (its schema: $(repr(schema)))" *
                            (old ? "; " * _refused_because(schema) * ": regenerate it: " *
                                   _regenerate_hint(path, "re-run the refinement step that made it from its own options (bin/refine.jl; " *
                                                          "the paper's experiments/scripts/radiometric_refinement.jl on its config, " *
                                                          "`--stage=refine --case=<its case> --force`)") : "")))
    end
    return r, VgtkIO.VgioStyle(r)
end

"""
    save_radiometric_camera(path, camera::CalibratedCamera; length_unit = mm, provenance = (;))

A [`CalibratedCamera`](@ref) as an `rc/radiometric_camera/v3.1` record (VisualGeometryToolkitIO's file boundary; see the file
header of `records.jl` for the record): its geometric camera as IO's camera or generic camera body, its aperture, focus surface
and vignetting (VisualRadiometryToolkitIO's body), its observation model and its render settings. Lengths in `length_unit`.
"""
function save_radiometric_camera(path::AbstractString, c::CalibratedCamera; length_unit = VgtkCore.mm, provenance::NamedTuple = (;))
    s = _style(length_unit)
    VgtkIO.write_record(path, VgtkIO.with_provenance(merge((schema = RECORD_SCHEMAS.radiometric_camera,), JSON.lower(s, c)), provenance); style = s)
    return nothing
end
"""
    load_radiometric_camera(path) -> CalibratedCamera

