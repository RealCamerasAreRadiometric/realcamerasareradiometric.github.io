# The paper's teaser (scripts/teaser.jl, src/teaser.jl; fig:teaser). Its stage teaser: the crops of a lens's panoramas and the
# paper's files from them and from the learned-texture figure's tables (src/paper_figures/teaser.jl on the fixtures
# test/fixtures/paper_figures/teaser/: every line but the generator line, every pixel of the strip), and the config of record with
# its driver's plan. No item reads a panorama of record: the fixture's stand-ins are of the paper's panel size.

@testitem "teaser: the paper's figure from its pieces, as in the paper; the crops" default_imports = false begin
    using Test
    using DrWatson
    using SHA: sha256
    using VisualGeometryToolkitEval.Experiments: run_isolated
    include(srcdir("experiments.jl"))
    include(srcdir("drivers.jl"))
    include(srcdir("panorama_example.jl"))
    include(srcdir("radiometric_refinement.jl"))
    include(srcdir("panorama_stitching.jl"))
    include(srcdir("paper_figures", "PaperFigures.jl"))
    include(srcdir("teaser.jl"))
    const P = PaperFigures
    F = projectdir("test", "fixtures", "paper_figures", "teaser")
    # the settings of the paper's figure: the config of record's, as its stage hands them
    cfg = load_teaser_config(projectdir("configs", "experiments", "teaser.toml")); t = cfg["teaser"]
    settings = teaser_settings(cfg)
    texture = joinpath(F, "texture")
    draw(out; opts...) = redirect_stdout(() -> PaperFigures.generate("teaser"; out, texture, opts...), devnull)

    @testset "the crops: a part of each panorama, brightened alike, cut to 8 bit" begin
        A = reshape(UInt8[10, 99, 100, 200, 255, 0, 1, 50, 128, 213, 214, 250], 2, 2, 3)        # rows × columns × 3
        @test crop_panorama(A, [0, 0, 2, 2], 1) == A
        @test crop_panorama(A, [0, 0, 2, 2], 1.2) == reshape(UInt8[12, 118, 120, 240, 255, 0, 1, 60, 153, 255, 255, 255], 2, 2, 3)   # 99 · 1.2 = 118.8 is cut, not rounded; above 255 kept at 255
        @test crop_panorama(A, [1, 0, 2, 1], 1) == A[1:1, 2:2, :]                                # first and past-last column and row, from 0
        @test_throws ArgumentError crop_panorama(A, [0, 0, 3, 2], 1)
        # the stage's crops of the fixture's stand-ins (they are of the paper's panel size): the whole image, unchanged
        dir = write_teaser_crops(joinpath(mktempdir(), "tables"), joinpath(F, "panoramas"), merge(t, Dict("box" => [0, 0, 460, 250], "gain" => 1)))
        @test sort(readdir(dir)) == ["pano-no-correction.png", "pano-our-correction.png"]
        @test P.load_png(joinpath(dir, "pano-no-correction.png")) == P.load_png(joinpath(F, "panoramas", "panorama_original.png"))
        @test P.load_png(joinpath(dir, "pano-our-correction.png")) == P.load_png(joinpath(F, "panoramas", "panorama_learned.png"))
        part = write_teaser_crops(joinpath(mktempdir(), "tables"), joinpath(F, "panoramas"), merge(t, Dict("box" => [100, 50, 300, 150])))
        @test size(P.load_png(joinpath(part, "pano-no-correction.png"))) == (100, 200, 3)
        @test_throws ArgumentError write_teaser_crops(mktempdir(), joinpath(F, "panoramas"), t)  # the record's box lies in a panorama of 3600 × 725 px, not in the stand-ins
    end

    crops = write_teaser_crops(joinpath(mktempdir(), "tables"), joinpath(F, "panoramas"), merge(t, Dict("box" => [0, 0, 460, 250], "gain" => 1)))
    @testset "the figure: the paper's files, every line but the generator line, every pixel of the strip" begin
        out = mktempdir()
        files = draw(out; crops, settings...)
        panels = ["teaser/pano-no-correction", "teaser/pano-our-correction"]
        @test sort(replace.(relpath.(files, out), '\\' => '/')) == sort([panels .* ".png"; panels .* ".tex"; "teaser/texture-strip.png"; "teaser/texture-strip.tex"; "teaser.tex"; "teaser-caption.tex"])
        for n in [panels .* ".tex"; "teaser/texture-strip.tex"; "teaser.tex"]
            mine = readlines(joinpath(out, n)); paper = readlines(joinpath(F, "expected", n))
            @test length(mine) == length(paper) && mine[2:end] == paper[2:end]
            @test occursin("generated by", mine[1]) && occursin("generated by", paper[1])
        end
        @test read(joinpath(out, "teaser-caption.tex")) == read(joinpath(F, "expected", "teaser-caption.tex"))     # the Python's caption, the panels brightened by 1.2
        @test read(joinpath(out, "teaser", "pano-no-correction.png")) == read(joinpath(crops, "pano-no-correction.png"))   # the crops as they are
        @test read(joinpath(out, "teaser", "pano-our-correction.png")) == read(joinpath(crops, "pano-our-correction.png"))
        hash, size_px, name = split(only(l for l in eachline(joinpath(F, "expected", "pixels.sha256")) if !startswith(l, "#") && !isempty(strip(l))))
        strip_image = P.load_png(joinpath(out, name))
        @test "$(size(strip_image, 2))x$(size(strip_image, 1))" == size_px == "3135x410"                            # 627 × 82 texels, 5 × 5 pixels each
        @test bytes2hex(sha256(vec(permutedims(strip_image, (3, 2, 1))))) == hash
        named = mktempdir(); draw(named; crops, settings..., generator = "a driver (its stage)")
        @test startswith(readline(joinpath(named, "teaser.tex")), "% teaser.tex — generated by a driver (its stage); do not edit.")
    end

    @testset "segments: two parts, each from its band on the texel grid; every setting is the caller's" begin
        out = mktempdir()
        two = [(; name = "ours", label = "ours", caption = "ours"), (; name = "truth", label = "ground truth", caption = "the design")]
        draw(out; crops, settings..., segments = two)
        ours = P.load_grey_png(joinpath(texture, "ours.png")); truth = P.load_grey_png(joinpath(texture, "truth.png"))
        @test P.load_grey_png(joinpath(out, "teaser", "texture-strip.png")) == repeat(hcat(ours[:, 1:314], truth[:, 315:627]); inner = (5, 5))   # 313.5 goes to the even number, as Python's round
        @test occursin("\\scriptsize ours}", read(joinpath(out, "teaser.tex"), String)) && !occursin("pinhole", read(joinpath(out, "teaser.tex"), String))
        @test !occursin("brightened", read(joinpath(draw(mktempdir(); crops, settings..., gain = 1)[end]), String))      # not brightened: the caption says nothing of it
        for k in keys(settings)
            @test_throws UndefKeywordError draw(mktempdir(); crops, Base.structdiff(settings, NamedTuple{(k,)})...)
        end
        @test_throws ErrorException draw(mktempdir(); crops, settings..., segments = [two[1], two[1]])
        @test_throws ErrorException draw(mktempdir(); crops = mktempdir(), settings...)         # no crops there
    end
end

@testitem "teaser: the config of record, a wrong one refused, the driver's plan" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    using VisualGeometryToolkitCore: thrown_message
    using VisualGeometryToolkitEval.Experiments: run_isolated
    include(srcdir("experiments.jl"))
    include(srcdir("drivers.jl"))
    include(srcdir("panorama_example.jl"))
    include(srcdir("radiometric_refinement.jl"))
    include(srcdir("panorama_stitching.jl"))
    include(srcdir("paper_figures", "PaperFigures.jl"))
    include(srcdir("teaser.jl"))
    path = projectdir("configs", "experiments", "teaser.toml")
    cfg = load_teaser_config(path)

    @testset "the config of record: the Tamron sweep's panoramas, the texture figure's bands, the paper's settings" begin
        t = cfg["teaser"]
        @test cfg["upstream"] == Dict("panorama_stitching" => "configs/experiments/panorama_stitching_fx3_tamron.toml",
                                      "texture_recovery" => "configs/experiments/texture_recovery_14mm_small.toml")
        @test t["box"] == [500, 0, 960, 250] && t["gain"] == 1.2 && t["segments"] == ["truth", "photograph", "pinhole", "ours"]
        @test t["asset_dir"] == "teaser" && t["texel_grid"] == "truth" && t["pixels_per_texel"] == 5
        @test [(p["panel"], p["candidate"]) for p in t["panels"]] == [("pano-no-correction", "original"), ("pano-our-correction", "learned")]
        # the strip's segments are bands of the learned-texture figure's stage ([bands] order of the texture config): its tables' files
        bands = TOML.parsefile(projectdir(cfg["upstream"]["texture_recovery"]))["bands"]
        @test issubset(t["segments"], bands["order"]) && t["texel_grid"] in bands["order"] && t["pixels_per_texel"] == bands["pixels_per_texel"]
        s = teaser_settings(cfg)
        @test [x.label for x in s.segments] == ["ground truth", "training photograph", "pinhole", "ours"] && s.lens == "Tamron 20\\,mm lens, \$f/2.8\$"
        @test isempty(cfg["inputs"])
    end

    function edited(change)
        c = TOML.parsefile(path); change(c)
        p = joinpath(mktempdir(), "teaser.toml")
        open(io -> TOML.print(io, c), p, "w")
        return p
    end
    refused(change) = thrown_message(() -> load_teaser_config(edited(change)))
    @testset "a wrong key, a missing one, a value that cannot be: refused by name" begin
        @test load_teaser_config(edited(identity)) == cfg                                  # the copy itself loads
        @test occursin("box", refused(c -> delete!(c["teaser"], "box")))                   # a missing key
        @test occursin("crop", refused(c -> c["teaser"]["crop"] = [500, 0, 960, 250]))     # an unknown one
        @test occursin("gain", refused(c -> delete!(c["teaser"], "gain"))) && occursin("gain", refused(c -> c["teaser"]["gain"] = 0))
        @test occursin("segments", refused(c -> delete!(c["teaser"], "segments"))) && occursin("segments", refused(c -> c["teaser"]["segments"] = ["truth", "truth"]))
        @test occursin("box", refused(c -> c["teaser"]["box"] = [960, 0, 500, 250]))
        @test occursin("caption", refused(c -> delete!(c["teaser"]["pinhole"], "caption")))
        @test occursin("two panels", refused(c -> pop!(c["teaser"]["panels"])))
        @test occursin("no config", refused(c -> c["upstream"]["texture_recovery"] = "configs/experiments/texture_recovery_none.toml"))
        @test occursin("panorama_crop", refused(c -> c["panorama_crop"] = Dict("gain" => 1.2)))   # an unknown table
        c = load_teaser_config(edited(c -> c["teaser"]["panels"][2]["candidate"] = "rooftop"))
        @test occursin("renders no candidate \"rooftop\"", thrown_message(() -> teaser_panoramas(c; path = "x.toml")))
    end

    @testset "the product: keyed by [teaser] and the two products it reads" begin
        withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => mktempdir(), "VGTK_SCRATCH" => "1") do
            panoramas = teaser_panoramas(cfg; path); bands = teaser_bands(cfg; path)
            p = teaser_product(cfg, panoramas, bands)
            @test p.name == "teaser" && p.experiment == "teaser" && p.output == "numbers.tex" && !haskey(p.record, "execution")
            @test panoramas.product.name == "panoramas" && bands.product.name == "bands" && bands.product.experiment == "texture_recovery"
            @test p.record["upstream"] == Dict("panoramas" => panoramas.product.key, "bands" => bands.product.key)
            c = load_teaser_config(edited(c -> c["teaser"]["gain"] = 1.0))
            @test teaser_product(c, panoramas, bands).key != p.key
        end
    end

    @testset "the driver: its plan lists the stage and runs nothing; a config without a setting of the figure is refused" begin
        function driver(args...)
            log = joinpath(mktempdir(), "plan.txt"); results = mktempdir()
            m = withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => results, "VGTK_SCRATCH" => "1") do
                open(io -> redirect_stdout(() -> run_isolated(scriptsdir("teaser.jl"); args = collect(String, args)), io), log, "w")
            end
            return m, read(log, String), results
        end
        m, log, results = driver("--plan")
        @test occursin(r"^\s+teaser\s+0/1 produced"m, log) && occursin("plan only", log)
        @test isempty([f for (_, _, fs) in walkdir(results) for f in fs])                  # a plan writes nothing
        @test Base.invokelatest(getfield, m, :GPU_STAGES) == Symbol[]
        script = read(scriptsdir("teaser.jl"), String)
        @test occursin("generator = \"experiments/\$DRIVER (stage teaser; T. Harder's teaser.py)\"", script)
        msg = try
            driver("--plan", "--config=$(edited(c -> delete!(c["teaser"], "box")))"); ""
        catch e
            while e isa LoadError
                e = e.error
            end
            sprint(showerror, e)
        end
        @test occursin("[teaser]", msg) && occursin("box", msg)
    end
end
