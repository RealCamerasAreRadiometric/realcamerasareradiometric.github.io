# The paper's detector-bias figure (fig:detector-bias, Fig. 4): the drawing code (src/paper_figures/detector_bias.jl, the port of
# T. Harder's detector_bias.py) and the experiment's config of record (configs/experiments/detector_bias.toml; scripts/detector_bias.jl,
# src/detector_bias.jl). The fixtures (fixtures/paper_figures/detector-bias-mitsuba/, its README) are the tables of the submitted
# figure and its files — its ten panel images as the checksums of their pixels (expected/pixels.sha256).
#
#   the figure: from the tables to the paper's files, every line but the generator line, every pixel, with the settings of the
#   config of record; what the drawing code refuses; its quantile and its JSON as NumPy's and Python's;
#   the config: its two cases, the keys of its products, and a wrong config refused. The driver's stages are listed by its plan
#   (drivers_tests.jl); the runs need the GPU and the renders and are not this suite.

@testitem "detector bias: the paper's figure, from its tables, as in the paper" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    using JSON: JSON
    using SHA: sha256
    include(srcdir("paper_figures", "PaperFigures.jl"))                 # the module PaperFigures: the generators and what they share
    const DB = PaperFigures.DetectorBias
    const FIXTURE = projectdir("test", "fixtures", "paper_figures", "detector-bias-mitsuba")
    # the paper's figure: [figure] of the config of record, handed to the generator as the driver's stage hands it
    const F = TOML.parsefile(projectdir("configs", "experiments", "detector_bias.toml"))["figure"]
    "The rows of the config of record as the part `figure` takes them, from the top."
    rows() = [(; files = t["files"], key_quantile = t["key_quantile"], notes = Dict{String, String}(t["notes"])) for t in (F[r] for r in F["order"])]
    settings() = (; asset_dir = F["asset_dir"], rows = rows(), bins = F["bins"], field_px = F["field_px"], render_px = F["render_px"], render_jpeg_quality = F["render_jpeg_quality"],
                    bias_min_features = F["bias_min_features"], calibration_min_points = F["calibration_min_points"], camera_gauge = true)
    "The generator with the settings of the config of record, but for those given, its printed summary silenced."
    generate(; opts...) = redirect_stdout(() -> PaperFigures.generate("detector-bias-mitsuba"; settings()..., opts...), devnull)

    # a comment line that names the generator: the one line a written file may differ in from the submitted one
    names_generator(l) = startswith(lstrip(l), "%") && occursin("generated by", l)
    "Whether two text files have the same lines, but for the comment lines that name the generator."
    function same_text(a, b)
        la = readlines(a); lb = readlines(b)
        return length(la) == length(lb) && all(x == y || (names_generator(x) && names_generator(y)) for (x, y) in zip(la, lb))
    end
    "The files under `dir`, as sorted paths relative to it."
    files_under(dir) = sort([relpath(joinpath(root, f), dir) for (root, _, files) in walkdir(dir) for f in files])
    """The submitted figure's images, as the fixture stores them (expected/pixels.sha256; the PNG files themselves are not stored): a
    line per image with the SHA-256 of its decoded pixels (8-bit RGB, row by row, three bytes per pixel), its size as
    <width>x<height> and its path among the figure's files. Returns path => (hash, size)."""
    function pixel_hashes()
        lines = [split(l) for l in eachline(joinpath(FIXTURE, "expected", "pixels.sha256")) if !isempty(strip(l)) && !startswith(l, "#")]
        return Dict(String(r[3]) => (String(r[1]), String(r[2])) for r in lines)
    end
    "Whether the image `img` (h × w × 3, 8 bit) is the submitted figure's image `name` (a path of `pixel_hashes`)."
    same_pixels(img, name) = (bytes2hex(sha256(vec(permutedims(img, (3, 2, 1))))), "$(size(img, 2))x$(size(img, 1))") == pixel_hashes()[name]

    data = joinpath(FIXTURE, "data"); expected = joinpath(FIXTURE, "expected")
    out = mktempdir()
    written = generate(; data, out)

    @testset "the figure, as in the paper: every line but the generator line, every pixel" begin
        renders = ["detector-bias-mitsuba/" * row["render"] for row in JSON.parsefile(joinpath(data, "rows.json"))["rows"]]
        images = sort(collect(keys(pixel_hashes())))
        @test length(renders) == 2 && length(images) == 10
        @test files_under(out) == sort([files_under(expected)[1:end-1]; images; renders])   # the fixture's files (but its list of checksums), the ten images, the renders
        @test sort([relpath(p, out) for p in written]) == files_under(out)                    # the generator returns what it wrote
        @test length(files_under(out)) == 2 + 2 * (6 + 5 + 1) + 2                             # figure and caption; per row 6 panels, 5 images and the render; two keys
        for f in filter(endswith(".tex"), files_under(out))
            @test endswith(f, "-caption.tex") ? read(joinpath(out, f)) == read(joinpath(expected, f)) : same_text(joinpath(out, f), joinpath(expected, f))
        end
        @test all(f -> same_pixels(PaperFigures.load_png(joinpath(out, f)), f), images)
        @test all(r -> read(joinpath(out, r)) == read(joinpath(data, basename(r))), renders)  # a render is its file, copied
        # the checksums see one pixel: a panel's image with one level more or less in one pixel is not the paper's
        changed = PaperFigures.load_png(joinpath(out, images[1])); changed[7, 11, 2] ⊻= 0x01
        @test !same_pixels(changed, images[1])
        # the generator line names what the caller says wrote the files; by default this file
        @test startswith(readline(joinpath(out, "detector-bias-mitsuba.tex")), "% detector-bias-mitsuba.tex — generated by experiments/src/paper_figures/detector_bias.jl; do not edit.")
    end

    @testset "the settings are the config's: the generator states none; its parts" begin
        @test F["asset_dir"] == "detector-bias-mitsuba" && [r.files for r in rows()] == ["opencv-aprilgrid-ocv14", "schops-siemensstars-spline-ds"]
        for k in keys(settings())                                           # each is required: without it nothing is drawn
            @test_throws UndefKeywordError PaperFigures.generate("detector-bias-mitsuba"; data, out = mktempdir(), (n => v for (n, v) in pairs(settings()) if n != k)...)
        end
        @test_throws ErrorException generate(; data, out = mktempdir(), part = "panels")
        @test_throws ErrorException generate(; data)                        # the part figure needs a folder to write into
        @test_throws ErrorException generate(; data, out = mktempdir(), rows = reverse(rows()))                              # not the tables' rows, in their order
        @test_throws ErrorException generate(; data, out = mktempdir(), rows = [merge(r, (; key_quantile = 1.5)) for r in rows()])
        @test_throws ErrorException generate(; data, out = mktempdir(), rows = [merge(r, (; notes = Dict("render" => "a note"))) for r in rows()])
    end

    @testset "db_nanquantile: numpy.nanquantile" begin
        @test DB.db_nanquantile([0.1, 0.5, NaN, 0.2, 0.9, 0.4], 0.98) == 0.868
        @test DB.db_nanquantile([3.0, 1.0, 2.0], 0.5) == 2.0 && DB.db_nanquantile([3.0, 1.0, 2.0, 10.0], 0.25) == 1.75
        @test DB.db_nanquantile([7.5, NaN], 0.98) == 7.5 && isnan(DB.db_nanquantile([NaN], 0.5))
        @test DB.db_nanquantile([0.3, 0.1, 0.7, 0.2], 0.0) == 0.1 && DB.db_nanquantile([0.3, 0.1, 0.7, 0.2], 1.0) == 0.7
        @test DB.db_nanmax([0.3, NaN, 0.7, 0.2]) == 0.7
    end

    @testset "db_pyjson: rows.json as Python's json.dump wrote it" begin
        # the stored rows.json was written by Python: read and written again here it must come out the same, character for character
        # (an object becomes the vector of its pairs in the file's order, the form db_pyjson takes it in)
        as_pairs(x) = x isa AbstractDict ? Pair{String, Any}[String(k) => as_pairs(val) for (k, val) in x] : x isa AbstractVector ? Any[as_pairs(val) for val in x] : x
        text = read(joinpath(data, "rows.json"), String)
        @test sprint(DB.db_pyjson, as_pairs(JSON.parse(text))) == text
        @test sprint(DB.db_pyjson, Pair{String, Any}["a" => String[], "b" => Pair{String, Any}[], "c" => "é\t€", "d" => NaN]) ==
              "{\n \"a\": [],\n \"b\": {},\n \"c\": \"\\u00e9\\t\\u20ac\",\n \"d\": NaN\n}"
    end
end

@testitem "detector bias: the config of record, its products' keys, a wrong config refused" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    include(srcdir("experiments.jl"))
    include(srcdir("drivers.jl"))
    include(srcdir("evaluation.jl"))
    include(srcdir("paper_figures", "PaperFigures.jl"))
    include(srcdir("detector_bias.jl"))

    path = projectdir("configs", "experiments", "detector_bias.toml")
    cfg = load_detector_bias_config(path)
    # the config with one change, in a folder of its own (a config of the driver is named detector_bias[_<variant>].toml)
    edited(f) = (c = TOML.parsefile(path); f(c); p = joinpath(mktempdir(), "detector_bias.toml"); open(io -> TOML.print(io, c), p, "w"); p)
    ocv, spline = "db_ocv14_mitsuba_fov", "db_spline_mitsuba_siemens_fisheye"

    @testset "the two cases: the detector-based starts on the rendered sets, the samples of the refinements of record" begin
        @test sort(collect(keys(cfg["cases"]))) == [ocv, spline] && !haskey(cfg, "kinds")
        @test cfg["cases"][ocv]["kind"] == "lens" && cfg["cases"][spline]["kind"] == "grid"
        @test all(c -> length(cfg["views"][cfg["cases"][c]["views"]]) == 200, (ocv, spline))
        o = RadiometricCamera.pipeline_options(cfg["cases"][ocv]["pipeline"]); s = RadiometricCamera.pipeline_options(cfg["cases"][spline]["pipeline"])
        @test o.masks.samples_per_view == 8192 && s.masks.samples_per_view == 16384           # [kinds] of the refinements of record
        @test o.io.channel == "RGB" && s.io.channel == "RGB" && o.lm.max_iter == 36 && s.lm.max_iter == 50
        @test s.masks.lens_coverage_scale == 0.9 && cfg["cases"][spline]["pipeline"]["grid"]["smoothness"]["weight"] == 0.01   # the paper's figure
        @test detector_bias_renders(cfg, ocv) == "renders_fov_aprilgrid" && detector_bias_renders(cfg, spline) == "renders_ds_siemens"
        # the camera a case starts from: a global model's record of the data root, a spline case's own start
        withenv("VGTK_DATA_ROOT" => mktempdir()) do
            @test detector_bias_start_camera(cfg, ocv, "s") == "lens:" * joinpath(data_root(), cfg["inputs"]["start_fov_aprilgrid"]["path"])
        end
        @test detector_bias_start_camera(cfg, spline, "s") == "grid:" * joinpath("s", "grid.json")
    end

    @testset "the products: an evaluation keyed by its start and refinement, the figure by its rows' evaluations and detections" begin
        e = detector_bias_evaluate_product(cfg, spline)
        @test e.name == "evaluate" && e.experiment == "detector_bias" && e.output == "scores.json"
        @test e.record["upstream"] == Dict("start" => start_product(cfg, spline).key, "refine" => refine_product(cfg, spline).key)
        @test e.record["truth"]["path"] == cfg["inputs"]["truth_ds_siemens"]["path"] && e.key != detector_bias_evaluate_product(cfg, ocv).key
        p = detector_bias_figures_product(cfg)
        @test p.name == "figures" && p.experiment == "detector_bias" && p.output == "numbers.tex" && !haskey(p.record, "execution")   # one result at any thread count
        @test p.record["upstream"] == Dict(c => detector_bias_evaluate_product(cfg, c).key for c in (ocv, spline)) && detector_bias_figure_cases(cfg) == [ocv, spline]
        @test sort(collect(keys(p.record["inputs"]))) == ["detections_ds_siemens", "detections_fov_aprilgrid"]
        @test all(i -> i["tier"] == "rc_synthetic" && occursin(r"^[0-9a-f]{64}$", i["sha256"]), values(p.record["inputs"]))
        key(f) = detector_bias_figures_product(load_detector_bias_config(edited(f))).key
        @test key(identity) == p.key                                                          # the config's content, wherever its file lies
        @test key(c -> c["figure"]["bins"] = [13, 9]) != p.key && key(c -> c["evaluate"]["gauge"] = "off") != p.key
        @test [r.files for r in detector_bias_rows(cfg)] == ["opencv-aprilgrid-ocv14", "schops-siemensstars-spline-ds"]
        @test [r.key_quantile for r in detector_bias_rows(cfg)] == [1.0, 0.98]
    end

    @testset "a wrong config is refused" begin
        refused(f) = (@test_throws ArgumentError load_detector_bias_config(edited(f)))
        @test load_detector_bias_config(edited(identity))["figure"] == cfg["figure"]         # the copy itself loads
        refused(c -> c["figure"]["colour"] = "red")                                           # an unknown key
        refused(c -> delete!(c["figure"], "bins"))                                            # a required key: the code has no value for it
        refused(c -> c["figures"] = Dict("a" => 1))                                           # an unknown table
        refused(c -> delete!(c["cases"][ocv], "truth")); refused(c -> c["cases"][ocv]["truth"] = "detections_fov_aprilgrid")   # no truth; an input of another stage
        refused(c -> c["cases"][ocv]["views"] = "none"); refused(c -> c["cases"][ocv]["kind"] = "spline")
        refused(c -> delete!(c["cases"][ocv]["pipeline"]["io"], "images"))                    # no renders
        refused(c -> c["evaluate"]["gauge"] = true); refused(c -> c["evaluate"]["truth"] = "truth_fov_aprilgrid")   # a switch is "on" | "off"; no other key
        refused(c -> c["figure"]["order"] = ["opencv_aprilgrid"])                             # a row's table that no row of the order names
        refused(c -> c["figure"]["field_px"] = [532]); refused(c -> c["figure"]["render_jpeg_quality"] = 0); refused(c -> c["figure"]["bias_min_features"] = 0)
        row(f) = c -> f(c["figure"]["schoeps_siemens"])
        refused(row(t -> delete!(t, "model"))); refused(row(t -> t["colour"] = "red"))
        refused(row(t -> t["case"] = "db_kb")); refused(row(t -> t["render"] = "image_7039.png"))       # no case; a view of the other case
        refused(row(t -> t["detections"] = "renders_ds_siemens"))                             # not the record of the detections
        refused(c -> delete!(c["inputs"]["detections_ds_siemens"], "sha256"))                 # not pinned by its content
        refused(row(t -> t["features"] = "blobs")); refused(row(t -> t["key_quantile"] = 0)); refused(row(t -> t["key_quantile"] = "max"))
        refused(row(t -> t["notes"] = Dict("render" => "a note"))); refused(row(t -> t["files"] = "opencv-aprilgrid-ocv14"))   # no such panel; the other row's files
    end
end
