# The paper's focus-surface figure (scripts/focus_surfaces.jl). Its stage panels: the paper's files from the figure's tables
# (src/paper_figures/focus_surfaces.jl on the fixtures test/fixtures/paper_figures/focus-surfaces/), the [panels] table of the config
# of record and what the stage does with two refined cameras (their dumps, the tables, the figure). Its stage figures, the earlier
# PNG: src/figures.jl focus_surface_figure. The driver's --plan in a process of its own is the drivers item's (drivers_tests.jl); the
# chrome tables moved with their stage (chrome_evaluation_paper_tests.jl).
@testitem "focus surfaces: the paper's figure, from its tables, as in the paper" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    include(srcdir("paper_figures", "PaperFigures.jl"))
    F = projectdir("test", "fixtures", "paper_figures", "focus-surfaces")
    asset_dir = TOML.parsefile(projectdir("configs", "experiments", "focus_surfaces.toml"))["panels"]["asset_dir"]   # the paper's figure: its name is the config of record's
    @test asset_dir == "focus-surfaces"
    out = mktempdir()
    files = redirect_stdout(() -> PaperFigures.generate("focus-surfaces"; data = joinpath(F, "tables"), out, asset_dir), devnull)
    panels = [joinpath("focus-surfaces", "fisheye.tex"), joinpath("focus-surfaces", "tamron.tex")]
    @test sort(relpath.(files, out)) == sort([panels; "focus-surfaces.tex"; "focus-surfaces-caption.tex"])
    # the figure and its panels: the paper's files, every line but the generator line (the first)
    same(mine, paper) = (a = split(mine, '\n'); b = split(paper, '\n'); length(a) == length(b) && a[2:end] == b[2:end])
    for n in [panels; "focus-surfaces.tex"]
        mine = read(joinpath(out, n), String); paper = read(joinpath(F, "expected", n), String)
        @test same(mine, paper)
        @test occursin("generated by", first(split(mine, '\n'))) && occursin("generated by", first(split(paper, '\n')))
    end
    # the caption (it has no generator line): the spacing of the lattice lines and the focus distance's range over all pixels (meta.toml)
    caption = read(joinpath(out, "focus-surfaces-caption.tex"), String)
    @test caption == read(joinpath(F, "expected", "focus-surfaces-caption.tex"), String)
    @test occursin("every 224\\,px (fisheye lens) and every 448\\,px (Tamron 20\\,mm lens)", caption)
    @test occursin("0.51 to 0.78\\,m (fisheye lens, \$f/4\$) and 0.21 to 0.33\\,m (Tamron 20\\,mm lens, \$f/8\$)", caption)
    # the name is the caller's to give: the files of another name read their panels from its folder
    other = mktempdir()
    redirect_stdout(() -> PaperFigures.generate("focus-surfaces"; data = joinpath(F, "tables"), out = other, asset_dir = "surfaces"), devnull)
    @test sort(readdir(other)) == ["surfaces", "surfaces-caption.tex", "surfaces.tex"] && sort(readdir(joinpath(other, "surfaces"))) == ["fisheye.tex", "tamron.tex"]
    @test occursin("\\input{\\rcfigdir/surfaces/fisheye}", read(joinpath(other, "surfaces.tex"), String))
    @test read(joinpath(other, "surfaces-caption.tex")) == read(joinpath(out, "focus-surfaces-caption.tex"))
    # a part without one of its settings is refused, and so is a part that is neither
    @test_throws UndefKeywordError PaperFigures.generate("focus-surfaces"; data = joinpath(F, "tables"), out = mktempdir())
    @test_throws UndefKeywordError PaperFigures.generate("focus-surfaces"; data = joinpath(F, "tables"), out = mktempdir(), part = "tables", spacing = 16)
    @test_throws ErrorException PaperFigures.generate("focus-surfaces"; data = joinpath(F, "tables"), out = mktempdir(), asset_dir, part = "panels")
end

@testitem "focus surfaces: the panels stage, its config and two cameras' dumps, tables and figure" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    import Printf
    using StaticArrays: SMatrix, SVector
    import RadiometricCamera as RC
    import VisualGeometryToolkitCore as VgtkCore
    import VisualRadiometryToolkitCore as VrtkCore
    using VisualGeometryToolkitEval.Experiments: run_isolated

    # the driver in a module of its own with both trees bound to empty folders (--plan: no stage runs), and what it printed
    function driver(args...)
        log = joinpath(mktempdir(), "plan.txt")
        m = withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => mktempdir()) do
            open(io -> redirect_stdout(() -> run_isolated(scriptsdir("focus_surfaces.jl"); args = collect(String, args)), io), log, "w")
        end
        return m, read(log, String)
    end
    # the driver's module is newer than the code that asks for it: a binding of it is read, a function of it called, in the latest world
    binding(mod, name::Symbol) = Base.invokelatest(getfield, mod, name)
    call(mod, name::Symbol, args...; kw...) = Base.invokelatest(binding(mod, name), args...; kw...)
    # what `f` throws (the error itself where loading a script wrapped it), or nothing
    function thrown(f)
        try
            f()
            return nothing
        catch e
            while e isa LoadError
                e = e.error
            end
            return e
        end
    end
    f4(v) = parse(Float64, Printf.@sprintf("%.4f", v))                    # a number as the tables print it: four decimals

    cfg = TOML.parsefile(projectdir("configs", "experiments", "focus_surfaces.toml"))
    m, plan = driver("--plan")
    G = binding(binding(m, :PaperFigures), :FocusSurfaces)                # the generator's module: its lattice lines
    panels = call(m, :panel_settings)                                     # the panels of the config of record, as the generator takes them

    @testset "the plan and the config of record" begin
        @test occursin(r"^\s+panels\s+0/1 produced"m, plan) && occursin(r"^\s+figures\s+0/1 produced"m, plan) && occursin("plan only", plan)
        P = binding(m, :CFG)["panels"]
        @test P == cfg["panels"] && P["asset_dir"] == "focus-surfaces" && P["spacing_px"] == 16
        @test [c["case"] for c in P["cases"]] == ["f4_fisheye_spline_warped", "sitla_spline_warped"]
        @test [c["config"] for c in P["cases"]] == ["configs/experiments/radiometric_refinement_vignetting.toml", "configs/experiments/radiometric_refinement.toml"]
        # the panels as the generator takes them are the table's cases, left to right: the paper's two
        @test [(l.lens, l.case, l.label, l.azimuth_deg, l.elevation_deg, l.grid_every) for l in panels] ==
              [("fisheye", "f4_fisheye_spline_warped", "Fisheye lens, f/4", 27.0, 14.4, 14), ("tamron", "sitla_spline_warped", "Tamron 20 mm lens, f/8", 27.0, 36.0, 28)]
        @test all(((l, c),) -> all(k -> getproperty(l, Symbol(k)) == c[k], ("lens", "case", "label", "azimuth_deg", "elevation_deg", "grid_every")), zip(panels, P["cases"]))
        # the two products are keyed apart; here both read the same two refinements
        pp = call(m, :panels_product); fp = call(m, :figures_product)
        @test pp.name == "panels" && fp.name == "figures" && pp.key != fp.key && pp.output == "numbers.tex"
        @test pp.record["upstream"] == fp.record["focus"] && length(pp.record["upstream"]) == 2
        @test binding(m, :GPU_STAGES) == Symbol[]                               # neither stage runs on a device
    end

    @testset "a wrong key of [panels] is refused" begin
        bad(change) = (t = deepcopy(cfg["panels"]); change(t); thrown(() -> call(m, :check_panels_table, t, "[panels]")))
        @test bad(identity) === nothing
        for (change, word) in ((t -> t["step_px"] = 16, "step_px"),                                     # an unknown key
                               (t -> delete!(t, "cases"), "cases"),                                    # a missing one
                               (t -> delete!(t, "asset_dir"), "asset_dir"),
                               (t -> t["spacing_px"] = 0, "spacing_px"),                               # no lattice
                               (t -> t["spacing_px"] = 16.0, "spacing_px"),
                               (t -> t["asset_dir"] = "", "asset_dir"),                                # no name
                               (t -> pop!(t["cases"]), "two panels"),                                  # the figure has two panels
                               (t -> push!(t["cases"], merge(t["cases"][1], Dict("lens" => "third"))), "two panels"),
                               (t -> t["cases"][1]["title"] = "fisheye", "title"),                     # an unknown key of an entry
                               (t -> delete!(t["cases"][2], "grid_every"), "grid_every"),              # a missing one
                               (t -> delete!(t["cases"][1], "label"), "label"),
                               (t -> t["cases"][1]["config"] = "configs/experiments/none.toml", "no config"),
                               (t -> t["cases"][2]["lens"] = "fisheye", "a lens of its own"),          # two panels, one file
                               (t -> t["cases"][1]["label"] = "Fisheye lens", "f/<f-number>"),         # a title without its f-number
                               (t -> t["cases"][1]["elevation_deg"] = 90.0, "elevation_deg"),          # not a view from the front left above
                               (t -> t["cases"][2]["azimuth_deg"] = -27.0, "azimuth_deg"),
                               (t -> t["cases"][1]["grid_every"] = 0, "grid_every"),
                               (t -> t["cases"][1]["grid_every"] = 14.0, "grid_every"))
            e = bad(change)
            @test e isa ArgumentError && occursin(word, e.msg)
        end
        # the keys are settings, not names the code knows: another name, lattice, order or view is a config like the one of record
        for change in (t -> t["asset_dir"] = "focus", t -> t["spacing_px"] = 24, t -> reverse!(t["cases"]), t -> t["cases"][1]["elevation_deg"] = 30)
            @test bad(change) === nothing
        end
        # through the driver: a config with a wrong key does not load, one without the table plans the PNG alone
        function with_config(change)
            c = deepcopy(cfg); change(c)
            path = joinpath(mktempdir(), "focus_surfaces.toml")
            open(io -> TOML.print(io, c), path, "w")
            return path
        end
        e = thrown(() -> driver("--plan", "--config=$(with_config(c -> c["panels"]["every"] = 14))"))
        @test e isa ArgumentError && occursin("every", e.msg) && occursin("[panels]", e.msg)
        e = thrown(() -> driver("--plan", "--config=$(with_config(c -> delete!(c["panels"], "spacing_px")))"))
        @test e isa ArgumentError && occursin("spacing_px", e.msg) && occursin("[panels]", e.msg)
        e = thrown(() -> driver("--plan", "--config=$(with_config(c -> c["panels"]["cases"][2]["case"] = "no_such_case"))"))
        @test e isa ArgumentError && occursin("has no case", e.msg) && occursin("[panels]", e.msg)
        m2, plan2 = driver("--plan", "--config=$(with_config(c -> delete!(c, "panels")))")
        @test occursin(r"^\s+panels\s+0/0 produced"m, plan2) && occursin(r"^\s+figures\s+0/1 produced"m, plan2)
        @test call(m2, :figures_product).key == call(m, :figures_product).key      # the PNG's product is keyed by [figures] alone
    end

    @testset "two cameras: their dumps, the figure's tables and its files" begin
        # two refined cameras as records: a Double Sphere camera on 960 × 640 px whose focus distance grows across the sensor (a sensor
        # spline through nine nodes), a flat vignetting; the second focuses nearer
        W, H = 960, 640; spacing = 16; nx, ny = W ÷ spacing, H ÷ spacing
        lens = VgtkCore.BoundedCamera(VgtkCore.CameraModel(VgtkCore.LogicalIntrinsics(VgtkCore.CameraCalibrationMat(SMatrix{3, 3}(600.0, 0, 0, 0, 600.0, 0, 480.0, 320.0, 1))),
                                                           VgtkCore.Lens(VgtkCore.DoubleSphere(0.2, 0.3))), VgtkCore.Size2(W, H))
        vig = VrtkCore.TensorProductVignetting((3, 3), VgtkCore.Rect(0, 0, W, H); degree = 2)
        camera(t̂) = RC.RadiometricCameraModel(lens, RC.Focus(RC.FocusSpline(VgtkCore.grid_nodes(3, VgtkCore.Rect(0, 0, W, H))), t̂), 0.004, vig)
        dir = mktempdir()
        function saved(name, model)                                           # the camera's record, as a refinement writes it
            path = joinpath(dir, name, "radiometric_camera.json"); mkpath(dirname(path))
            RC.save_radiometric_camera(path, RC.CalibratedCamera(model, RC.ObservationModel(RC.NoSensorRecord(), RC.Decoded(false), :RGB), RC.RenderSettings(; n_𝐩 = 1, n_ρ = 2, n_φ = 6)))
            return path
        end
        records = [l.case => saved(l.case, camera([1 / (near + 0.03 * k) for k in 0:8])) for (l, near) in zip(panels, (0.5, 0.25))]
        out = joinpath(dir, "product")
        files = redirect_stdout(() -> call(m, :focus_panels, records, out; asset_dir = "focus-surfaces", spacing, panels), devnull)
        @test sort(relpath.(files, out)) == sort(joinpath.("assets", ["focus-surfaces.tex", "focus-surfaces-caption.tex", joinpath("focus-surfaces", "fisheye.tex"), joinpath("focus-surfaces", "tamron.tex")]))
        @test all(isfile, files)
        meta = TOML.parsefile(joinpath(out, "tables", "meta.toml"))
        @test meta["spacing_px"] == spacing && meta["order"] == ["fisheye", "tamron"]
        # the stage names itself as the generator of its files, the tables and the figure
        @test occursin("(experiments/scripts/focus_surfaces.jl (stage panels;", readline(joinpath(out, "tables", "meta.toml")))
        @test all(f -> startswith(readline(joinpath(out, "assets", f)), "% $f — generated by experiments/scripts/focus_surfaces.jl (stage panels;"),
                  ("focus-surfaces.tex", "focus-surfaces/fisheye.tex", "focus-surfaces/tamron.tex"))
        for ((case, rec), l) in zip(records, panels)
            model = RC.load_radiometric_camera(rec).model                     # the camera as the stage read it
            # the dump: the lattice's size, then X, Y, Z and the focus distance, each sample the camera's own focus point of its pixel
            nxy, X, Y, Z, D = open(joinpath(out, "dump", case * ".f64")) do io
                n = (Int(ltoh(read(io, Int64))), Int(ltoh(read(io, Int64))))
                A = [ltoh.(read!(io, Matrix{Float64}(undef, n...))) for _ in 1:4]
                eof(io) || error("the dump holds more than its four arrays")
                (n, A...)
            end
            @test nxy == (nx, ny) && all(isfinite, D)
            for (i, j) in ((1, 1), (nx, 1), (17, 23), (nx, ny))
                p = SVector((i - 0.5) * spacing, (j - 0.5) * spacing)             # sample (i − 1, j − 1), counted from 0
                @test SVector(X[i, j], Y[i, j], Z[i, j]) == RC.𝔣(model, p) && D[i, j] == 1 / RC.t̂(model, p)
            end
            @test maximum(abs.(sqrt.(X .^ 2 .+ Y .^ 2 .+ Z .^ 2) .- D)) < 1e-12     # a central camera: the point lies at its focus distance
            @test minimum(D) < maximum(D) - 0.1                                   # the focus distance grows across the sensor
            # the tables: the lens's lattice and its focus distance over all samples; the samples on the drawn lattice lines only
            L = meta["lenses"][l.lens]
            @test L["case"] == case && (L["nx"], L["ny"], L["imaged"], L["every"]) == (nx, ny, nx * ny, l.grid_every)
            @test L["label"] == l.label && L["view"] == [l.azimuth_deg, l.elevation_deg]
            @test L["focus_min"] == f4(minimum(D)) && L["focus_max"] == f4(maximum(D))
            rows = [split(r, '\t') for r in eachline(joinpath(out, "tables", l.lens * ".tsv")) if !startswith(r, "#")]
            ii = call(G, :focus_lines, nx, l.grid_every); jj = call(G, :focus_lines, ny, l.grid_every)
            @test length(rows) == count(((i, j),) -> i in ii || j in jj, Iterators.product(0:nx-1, 0:ny-1))
            @test all(r -> parse(Int, r[1]) in ii || parse(Int, r[2]) in jj, rows)
            @test all(r -> (i = parse(Int, r[1]) + 1; j = parse(Int, r[2]) + 1; parse.(Float64, r[3:5]) == f4.([X[i, j], Y[i, j], Z[i, j]])), rows)
            # the panel: a filled cell between each pair of neighbouring lines along both axes, and the camera's dot
            panel = read(joinpath(out, "assets", "focus-surfaces", l.lens * ".tex"), String)
            @test count("\\path[rcfs,", panel) == (length(ii) - 1) * (length(jj) - 1) && count("\\fill (axis cs:0,0,0)", panel) == 1
        end
        figure = read(joinpath(out, "assets", "focus-surfaces.tex"), String)
        @test occursin("\\input{\\rcfigdir/focus-surfaces/fisheye}", figure) && occursin("\\input{\\rcfigdir/focus-surfaces/tamron}", figure)
        # a dump takes four arrays of one size; a camera that focuses nowhere (t̂ < 0 on all of its sensor) has no surface
        z = zeros(2, 2)
        @test_throws ArgumentError call(m, :write_focus_dump, joinpath(dir, "bad.f64"), z, z, z, zeros(3, 2))
        nowhere = saved("nowhere", camera(fill(-1.0, 9)))
        e = thrown(() -> redirect_stdout(() -> call(m, :focus_panels, [l.case => nowhere for l in panels], joinpath(dir, "none"); asset_dir = "focus-surfaces", spacing, panels), devnull))
        @test e isa ArgumentError && occursin("no pixel", e.msg)
        # the cameras are the panels' cases, in their order
        e = thrown(() -> call(m, :focus_panels, reverse(records), joinpath(dir, "reversed"); asset_dir = "focus-surfaces", spacing, panels))
        @test e isa ArgumentError && occursin("in this order", e.msg) && !ispath(joinpath(dir, "reversed"))
    end
end

@testitem "focus surfaces figure: a synthetic sphere and plane" default_imports = false begin
    using Test
    using DrWatson
    include(srcdir("experiments.jl"))
    include(srcdir("figures.jl"))
    using .Figures: focus_surface_figure
    # a sphere of radius 0.7 m about the camera over a 120° cone and a plane at z = 0.5 m over a 40° one, NaN outside: both render
    sphere = let n = 25, X = fill(NaN, n, n), Y = copy(X), Z = copy(X), D = copy(X)
        for j in 1:n, i in 1:n
            θx = (i - (n + 1) / 2) / n * 2π / 3; θy = (j - (n + 1) / 2) / n * 2π / 3
            d = [tan(θx), tan(θy), 1.0]; d ./= sqrt(sum(abs2, d)); hypot(θx, θy) <= π / 3 || continue
            X[i, j], Y[i, j], Z[i, j], D[i, j] = (0.7 .* d)..., 0.7
        end
        ("fisheye · sphere", X, Y, Z, D)
    end
    plane = let n = 25, X = fill(NaN, n, n), Y = copy(X), Z = copy(X), D = copy(X)
        for j in 1:n, i in 1:n
            x = (i - (n + 1) / 2) / n * 0.4; y = (j - (n + 1) / 2) / n * 0.3
            X[i, j], Y[i, j], Z[i, j], D[i, j] = x, y, 0.5, hypot(x, y, 0.5)
        end
        ("Tamron · plane", X, Y, Z, D)
    end
    # the gridded look (2026-11-15): no colour bar, a line along every grid_every-th row and column, a view elevation per panel
    fig = focus_surface_figure([sphere, plane]; size_in = (3.3, 1.75), dpi = 60, grid_every = 6, elevations_deg = [14.4, 36.0])
    out = Figures._save(fig, "focus.png", mktempdir())
    @test isfile(out) && filesize(out) > 1000
    @test (img = Figures.PNGFiles.load(out); (size(img, 2), size(img, 1))) == (198, 105)   # 3.3 × 1.75 in at 60 dpi
    @test !any(x -> x isa Figures.Makie.Colorbar, fig.content) && count(x -> x isa Figures.Makie.Axis3, fig.content) == 2
    @test_throws ArgumentError focus_surface_figure([]; dpi = 60)
    @test_throws ArgumentError focus_surface_figure([("empty", fill(NaN, 2, 2), fill(NaN, 2, 2), fill(NaN, 2, 2), fill(NaN, 2, 2))]; dpi = 60)
    @test_throws ArgumentError focus_surface_figure([sphere, plane]; dpi = 60, elevations_deg = [14.4])   # one elevation per panel
    @test_throws ArgumentError focus_surface_figure([sphere]; dpi = 60, grid_every = 1)
end
