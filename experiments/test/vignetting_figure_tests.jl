        @test [round(thin_lens_focal_px(options(k), W, H); digits = 1) for k in order] == [1754.7, 933.2, 2534.2]
        # f_mm over the pixel pitch of the run's sensor (RadiometricCamera's run_sensor: the sensor width over the photographs' width)
        o = options("tamron")
        @test thin_lens_focal_px(o, W, H) ≈ o.camera.f_mm / o.camera.sensor_mm * W rtol = 1e-14
        @test thin_lens_focal_px(o, W ÷ 2, H ÷ 2) ≈ thin_lens_focal_px(o, W, H) / 2 rtol = 1e-14   # photographs of half the width: pixels twice as large
        # a lens's focal length from its refinement case and its refined camera, whose sensor gives the photographs' size
        K = VgtkCore.CameraCalibrationMat(SMatrix{3, 3}(2480.0, 0, 0, 0, 2480.0, 0, W / 2, H / 2, 1))
