        @test Base.invokelatest(Base.invokelatest(getfield, m, :figures_product)).name == "figures"
        msg = try
            driver("--plan", "--config=$(edited(c -> delete!(c["figure"], "asset_dir")))"); ""
        catch e
            while e isa LoadError
                e = e.error
            end
            sprint(showerror, e)
        end
        @test occursin("[figure]", msg) && occursin("asset_dir", msg)
    end
