        @test f.f_mm == 21.1975 && f.f_px == thin_lens_focal_px(o, W, H)               # not the camera's own intrinsics (2480 px)
    end

    @testset "the driver: its plan lists the stage and runs nothing; a config without a setting of the figure is refused" begin
        # the driver in a module of its own with both trees bound to empty folders (--plan: no stage runs), and what it printed
        function driver(args...)
            log = joinpath(mktempdir(), "plan.txt"); results = mktempdir()
            m = withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => results, "VGTK_SCRATCH" => "1") do
                open(io -> redirect_stdout(() -> run_isolated(scriptsdir("vignetting_figure.jl"); args = collect(String, args)), io), log, "w")
            end
            return m, read(log, String), results
        end
        m, log, results = driver("--plan")
        @test occursin(r"^\s+figures\s+0/1 produced"m, log) && occursin("plan only", log)
        @test isempty([f for (_, _, fs) in walkdir(results) for f in fs])                  # a plan writes nothing
        @test Base.invokelatest(getfield, m, :GPU_STAGES) == Symbol[]
        # the stage names itself as the generator of the figure's files, and hands the generator the settings of the config
        script = read(scriptsdir("vignetting_figure.jl"), String)
        @test Base.invokelatest(getfield, m, :DRIVER) == "scripts/vignetting_figure.jl"
