# The supplement's panoramas figure (scripts/panorama_figure.jl, src/panorama_figure.jl; panoramas-james.tex). Its stage figures:
# the figure's files from the lenses' panoramas (src/paper_figures/panoramas.jl on the small synthetic panoramas of
# test/fixtures/paper_figures/panoramas/, as the Python generator drew them: every line but the generator line, every pixel), and
# the config of record with its driver's plan. No item reads a panorama of record: they are 3600 px wide.

@testitem "panorama figure: the figure from small synthetic panoramas, as the Python generator drew it" default_imports = false begin
    using Test
    using DrWatson
    using SHA: sha256
    include(srcdir("experiments.jl"))
    include(srcdir("drivers.jl"))
    include(srcdir("panorama_example.jl"))
    include(srcdir("radiometric_refinement.jl"))
    include(srcdir("panorama_stitching.jl"))
    include(srcdir("panorama_figure.jl"))
    include(srcdir("paper_figures", "PaperFigures.jl"))
    F = projectdir("test", "fixtures", "paper_figures", "panoramas")
    # the settings of the paper's figure: the config of record's, as its stage hands them
    settings = panorama_figure_settings(load_panorama_figure_config(projectdir("configs", "supplement", "panorama_figure.toml")))
    panoramas = Dict(k => joinpath(F, "panoramas", k) for k in settings.order)
    draw(out; opts...) = redirect_stdout(() -> PaperFigures.generate("panoramas"; out, opts...), devnull)
    "The SHA-256 of an image's pixels (h × w × 3, 8 bit) taken row by row, three bytes per pixel — as a fixture's pixels.sha256 lists it."
    pixel_sha256(img) = bytes2hex(sha256(vec(permutedims(img, (3, 2, 1)))))
    "What the files under `out` differ in from the fixture folder `expected` (its .tex files and the images of its pixels.sha256); empty when they are the same."
    function differences(out, expected, written)
        found = String[]
        refs = sort([replace(relpath(joinpath(r, f), expected), '\\' => '/') for (r, _, fs) in walkdir(expected) for f in fs if endswith(f, ".tex")])
        hashes = [split(l) for l in eachline(joinpath(expected, "pixels.sha256")) if !isempty(strip(l)) && !startswith(l, "#")]
        sort(replace.(relpath.(written, out), '\\' => '/')) == sort([refs; [String(h[3]) for h in hashes]]) || push!(found, "the files written are not the fixture's")
        for f in refs
            a = readlines(joinpath(out, f)); b = readlines(joinpath(expected, f))
            endswith(f, "-caption.tex") ? (a == b || push!(found, "$f: differs")) :                        # a caption has no generator line
                (length(a) == length(b) && a[2:end] == b[2:end] && occursin("generated by", a[1]) || push!(found, "$f: differs beside its generator line"))
        end
        for (hash, size_px, f) in hashes
            img = PaperFigures.load_png(joinpath(out, f))
            "$(size(img, 2))x$(size(img, 1))" == size_px && pixel_sha256(img) == hash || push!(found, "$f: its pixels differ from the reference's")
            occursin("sRGB", String(read(joinpath(out, f)))) && push!(found, "$f: carries colour chunks")
        end
        return found
    end

    @testset "three lenses, the display curve of record, panels of 98 px" begin
        out = mktempdir()
        v = differences(out, joinpath(F, "expected", "three-lenses"), draw(out; panoramas, settings..., width = 98))
        foreach(x -> @info(x), v)
        @test isempty(v)
        # a panel's height: 98 · 99 / 252 = 38.5, 98 · 117 / 252 = 45.5 and 98 · 50 / 200 = 24.5 go to the even number, as Python's round
        @test [size(PaperFigures.load_png(joinpath(out, "panoramas-james", "$p-no-correction.png")))[1:2] for p in ("sigma14", "fisheye", "tamron20")] == [(38, 98), (46, 98), (24, 98)]
        # a caller that names itself (a driver's stage): the files' first lines name it
        named = mktempdir(); draw(named; panoramas, settings..., width = 98, generator = "a driver (its stage)")
        @test startswith(readline(joinpath(named, "panoramas-james.tex")), "% panoramas-james.tex — generated by a driver (its stage); do not edit.")
    end

    @testset "two lenses in another order, another display curve, panels of 64 px" begin
        out = mktempdir()
        v = differences(out, joinpath(F, "expected", "two-lenses"), draw(out; panoramas, settings..., order = ["tamron", "fourteen"], gain = 4, gamma = 2.2, width = 64))
        foreach(x -> @info(x), v)
        @test isempty(v)
    end

    @testset "the display curve, as NumPy took it in single precision" begin
        PAN = PaperFigures.Panoramas
        @test PAN.panorama_display_table(1, 1) == 0:255
        @test PAN.panorama_display_table(2.5, 1.5)[[0, 1, 64, 128, 254, 255] .+ 1] == [0, 12, 151, 204, 255, 255]
        @test PAN.panorama_display_table(4, 2.2)[[0, 1, 64, 128, 254, 255] .+ 1] == [0, 38, 198, 231, 255, 255]
        @test issorted(PAN.panorama_display_table(2.5, 1.5))
    end

    @testset "every setting is the caller's; a lens without a folder, a display curve that is not positive, a third column" begin
        for k in keys(settings)
            @test_throws UndefKeywordError draw(mktempdir(); panoramas, Base.structdiff(settings, NamedTuple{(k,)})...)
        end
        @test_throws ErrorException draw(mktempdir(); panoramas = Dict("fourteen" => panoramas["fourteen"]), settings...)
        @test_throws ErrorException draw(mktempdir(); panoramas, settings..., gain = 0)
        @test_throws ErrorException draw(mktempdir(); panoramas, settings..., columns = [settings.columns; settings.columns[1:1]])
        @test_throws ErrorException draw(mktempdir(); panoramas, settings..., columns = [(; panel = "x", candidate = "rooftop", title = "x"), settings.columns[2]])   # no such panorama
    end
end

@testitem "panorama figure: the config of record, a wrong one refused, the driver's plan" default_imports = false begin
    using Test
    using DrWatson
    using TOML: TOML
    using VisualGeometryToolkitCore: thrown_message
    using VisualGeometryToolkitEval.Experiments: run_isolated
    include(srcdir("experiments.jl"))
    include(srcdir("drivers.jl"))
    include(srcdir("panorama_example.jl"))
    include(srcdir("radiometric_refinement.jl"))
    include(srcdir("panorama_stitching.jl"))
    include(srcdir("panorama_figure.jl"))
    path = projectdir("configs", "supplement", "panorama_figure.toml")
    cfg = load_panorama_figure_config(path)

    @testset "the config of record: the three lenses' panoramas, the paper's settings" begin
        @test cfg["figure"] == Dict("asset_dir" => "panoramas-james", "order" => ["fourteen", "fisheye", "tamron"], "gain" => 2.5, "gamma" => 1.5, "width_px" => 1400,
                                    "columns" => [Dict("panel" => "no-correction", "candidate" => "original", "title" => "no vignetting correction"),
                                                  Dict("panel" => "our-correction", "candidate" => "learned", "title" => "our vignetting correction")])
        @test [cfg["lenses"][k]["config"] for k in cfg["figure"]["order"]] == ["configs/experiments/panorama_stitching_fx3_$l.toml" for l in ("14mm", "fisheye", "tamron")]
        s = panorama_figure_settings(cfg)
        @test s.labels == Dict("fourteen" => ("Sigma", "14\\,mm lens"), "fisheye" => ("fisheye", "lens"), "tamron" => ("Tamron", "20\\,mm lens"))
        @test s.panels == Dict("fourteen" => "sigma14", "fisheye" => "fisheye", "tamron" => "tamron20") && s.apertures["tamron"] == "\$f/2.8\$" && s.width == 1400
        @test isempty(cfg["inputs"])
    end

    # the config with one change, written beside nothing else (a config of the driver is named panorama_figure[_<variant>].toml)
    function edited(change)
        c = TOML.parsefile(path); change(c)
        p = joinpath(mktempdir(), "panorama_figure.toml")
        open(io -> TOML.print(io, c), p, "w")
        return p
    end
    refused(change) = thrown_message(() -> load_panorama_figure_config(edited(change)))
    @testset "a wrong key, a missing one, a value that cannot be: refused by name" begin
        @test load_panorama_figure_config(edited(identity)) == cfg                         # the copy itself loads
        @test occursin("width_px", refused(c -> delete!(c["figure"], "width_px")))         # a missing key
        @test occursin("width", refused(c -> c["figure"]["width"] = 1400))                 # an unknown one
        @test occursin("display", refused(c -> c["display"] = Dict("gain" => 2.5)))        # an unknown table
        @test occursin("aperture", refused(c -> delete!(c["lenses"]["tamron"], "aperture")))
        @test occursin("two lines", refused(c -> c["lenses"]["fisheye"]["label"] = "fisheye lens"))
        @test occursin("a panel of its own", refused(c -> c["lenses"]["fourteen"]["panel"] = "fisheye"))
        @test occursin("no config", refused(c -> c["lenses"]["fourteen"]["config"] = "configs/experiments/panorama_stitching_fx3_16mm.toml"))
        @test occursin("order", refused(c -> c["figure"]["order"] = ["fourteen", "fisheye"]))
        @test occursin("two columns", refused(c -> push!(c["figure"]["columns"], Dict("panel" => "x", "candidate" => "learned", "title" => "x"))))
        @test occursin("title", refused(c -> delete!(c["figure"]["columns"][1], "title")))
        @test occursin("gamma", refused(c -> c["figure"]["gamma"] = 0))
        @test occursin("width_px", refused(c -> c["figure"]["width_px"] = 1400.5))
        # a candidate the lens's panorama config does not render: refused where the panoramas are looked up
        c = load_panorama_figure_config(edited(c -> c["figure"]["columns"][2]["candidate"] = "rooftop"))
        @test occursin("renders no candidate \"rooftop\"", thrown_message(() -> panorama_figure_sources(c; path = "x.toml")))
    end

    @testset "the product: keyed by the lenses, the settings and the panoramas it reads; a supplement experiment's" begin
        withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => mktempdir(), "VGTK_SCRATCH" => "1") do
            sources = panorama_figure_sources(cfg; path)
            p = panorama_figure_product(cfg, sources)
            @test p.name == "figures" && p.experiment == "supplement/panorama_figure" && p.output == "numbers.tex"
            @test p.record["upstream"] == Dict(k => s.product.key for (k, s) in sources) && !haskey(p.record, "execution")
            @test all(s -> s.product.name == "panoramas" && s.product.experiment == "panorama_stitching", values(sources))
            @test allunique(s.product.key for s in values(sources))
            key(change) = (c = load_panorama_figure_config(edited(change)); panorama_figure_product(c, panorama_figure_sources(c)).key)
            @test key(identity) == p.key
            @test key(c -> c["figure"]["gain"] = 3.0) != p.key && key(c -> c["lenses"]["tamron"]["aperture"] = "\$f/4\$") != p.key
        end
    end

    @testset "the driver: its plan lists the stage and runs nothing; a config without a setting of the figure is refused" begin
        function driver(args...)
            log = joinpath(mktempdir(), "plan.txt"); results = mktempdir()
            m = withenv("VGTK_DATA_ROOT" => mktempdir(), "VGTK_RESULTS_ROOT" => results, "VGTK_SCRATCH" => "1") do
                open(io -> redirect_stdout(() -> run_isolated(scriptsdir("panorama_figure.jl"); args = collect(String, args)), io), log, "w")
            end
            return m, read(log, String), results
        end
        m, log, results = driver("--plan")
        @test occursin(r"^\s+figures\s+0/1 produced"m, log) && occursin("plan only", log)
        @test isempty([f for (_, _, fs) in walkdir(results) for f in fs])                  # a plan writes nothing
        @test Base.invokelatest(getfield, m, :GPU_STAGES) == Symbol[]
        script = read(scriptsdir("panorama_figure.jl"), String)
        @test occursin("generator = \"experiments/\$DRIVER (stage figures; T. Harder's panorama_pgf.py)\"", script)
        msg = try
            driver("--plan", "--config=$(edited(c -> delete!(c["figure"], "asset_dir")))"); ""
        catch e
            while e isa LoadError
                e = e.error
            end
            sprint(showerror, e)
        end
        @test occursin("[figure]", msg) && occursin("asset_dir", msg)
    end
end
