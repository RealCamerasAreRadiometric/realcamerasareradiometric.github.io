# The paper's learned-texture figure (fig:texture-learned, Fig. 7 right): the generator's two parts (src/paper_figures/texture_learned.jl,
# the port of T. Harder's texture_learned.py) and the stage bands of scripts/texture_recovery.jl that runs them on the driver's own
# products (configs/experiments/texture_recovery_14mm_small.toml, [bands]). The fixtures (fixtures/paper_figures/texture-learned/, its
# README) are the records of the texture run the submitted figure was drawn from, cut to what the figure reads, the photograph band
# as its author-side step wrote it (an input of record), and the submitted figure's files — its four images as the checksums of
# their pixels (expected/pixels.sha256).
#
#   the generator: from the run's records to the tables — the bands' rows, the training photograph (the rule, and the record of its
#   band checked against it), the textures' errors — and from the tables to the paper's files, every line but the generator line,
#   every pixel; what it refuses. Every setting is handed to it: those of the paper's figure are read from the config of record;
#   the stage: its table checked when the config is loaded, its product keyed by the table, the photograph band's content and the
#   three products it reads, and the paper's files written from them through the config's inputs. The driver is loaded in a
#   module of its own (--plan: nothing run); no product is produced.

# The fixture and the comparison of a written file with the submitted one, shared by the two items.
@testsetup module TextureLearnedFigure
    using DrWatson
    using SHA: sha256
    import ColorTypes, PNGFiles

    "The figure's fixture folder (test/fixtures/paper_figures/texture-learned)."
    const FIXTURE = projectdir("test", "fixtures", "paper_figures", "texture-learned")
    "The fixture run's records as the generator's part `tables` takes them: the evaluate product, the init product's poses, the refine product's roles."
    const RECORDS = (; evaluate = joinpath(FIXTURE, "run", "evaluate"), poses = joinpath(FIXTURE, "run", "init", "poses.json"),
                     roles = joinpath(FIXTURE, "run", "refine", "page.json"))

    "The photograph band's two files (name in the fixture => name the author-side step gave it), and `edit` of the record's text."
    photograph_files(; edit = identity) = ("photograph.png" => read(joinpath(FIXTURE, "photograph", "photograph.png")),
                                           "meta.toml" => Vector{UInt8}(edit(read(joinpath(FIXTURE, "photograph", "meta.toml.txt"), String))))
    "The photograph band as the author-side step wrote it, in a folder of its own (photograph.png, meta.toml); `edit` changes the record's text."
    function photograph_folder(; edit = identity)
        dir = mktempdir()
        foreach(((n, bytes),) -> write(joinpath(dir, n), bytes), photograph_files(; edit))
        return dir
    end

    # a comment line that names the generator: the one line a written file may differ in from the submitted one
    names_generator(l) = startswith(lstrip(l), "%") && occursin("generated by", l)
    "Whether two text files have the same lines, but for the comment lines that name the generator."
    function same_text(a, b)
        la = readlines(a); lb = readlines(b)
        return length(la) == length(lb) && all(x == y || (names_generator(x) && names_generator(y)) for (x, y) in zip(la, lb))
    end
    "The figure's files under a folder, relative to it: the main file, a file and an image per band, the caption."
    figure_files(bands) = ["texture-learned.tex"; ["texture-learned/$b.$e" for b in bands for e in ("tex", "png")]; "texture-learned-caption.tex"]

    """
    The submitted figure's images, as the fixture stores them (expected/pixels.sha256; the PNG files themselves are not stored): a
    line per image with the SHA-256 of its decoded pixels (8-bit grey, row by row, one byte per pixel), its size as
    <width>x<height> and its path among the figure's files. Returns path => (hash, size).
    """
    function pixel_hashes()
        rows = [split(l) for l in eachline(joinpath(FIXTURE, "expected", "pixels.sha256")) if !isempty(strip(l)) && !startswith(l, "#")]
        return Dict(String(r[3]) => (String(r[1]), String(r[2])) for r in rows)
    end
    "Whether the PNG `file` is the submitted figure's image `name` (a path of `pixel_hashes`): an 8-bit grey image of its size, with its pixels."
    function same_pixels(file, name)
        a = PNGFiles.load(file)
        eltype(a) == ColorTypes.Gray{ColorTypes.N0f8} || return false
        img = collect(reinterpret(UInt8, a))                            # h × w, row 1 = top
        return (bytes2hex(sha256(vec(permutedims(img)))), "$(size(img, 2))x$(size(img, 1))") == pixel_hashes()[name]
    end
    export FIXTURE, RECORDS, photograph_files, photograph_folder, same_text, figure_files, pixel_hashes, same_pixels
end

