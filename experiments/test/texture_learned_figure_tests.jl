            eight = sort(fit; by = v -> G.texlearned_pose(v)[1])[1:8]
            return splitext(eight[argmin([sum(G.texlearned_pose(v)[1:2]) for v in eight])]["view"])[1]
        end
        @test chosen(page["roles"]) == "DSC03316"
        # a record of another photograph than the chosen one is refused, naming both
        m = message(() -> tables_of(photograph = photograph_folder(edit = t -> replace(t, "DSC03316.ARW" => "DSC03307.ARW"))))
