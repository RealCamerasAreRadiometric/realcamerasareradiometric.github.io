            @test occursin(k, check(c -> delete!(c["bands"], k)))            # every key is required
        end
        @test occursin("order =", check(c -> c["bands"]["order"] = ["truth", "truth"]))
        @test occursin("order =", check(c -> c["bands"]["order"] = String[]))
