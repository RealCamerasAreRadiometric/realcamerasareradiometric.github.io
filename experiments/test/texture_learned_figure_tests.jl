    @testset "the paper's files from a run's records, through the config's inputs" begin
        # a data root that holds the photograph band where the config's two inputs name it
        function data_root(files = photograph_files())
            root = mktempdir()
            for (k, (_, bytes)) in zip(the(:BANDS_INPUT_KEYS), files)
                f = joinpath(root, cfg["inputs"][t[k]]["path"]); mkpath(dirname(f)); write(f, bytes)
            end
            return root
        end
        dir = mktempdir()
        written = withenv("VGTK_DATA_ROOT" => data_root()) do              # the fixture's band is the input of record: its sha256 is the config's
            call(:write_bands, t, dir; RECORDS...)
        end
        bands = t["order"]; expected = joinpath(FIXTURE, "expected")
        @test sort(written) == sort([[joinpath(dir, "tables", "$b.png") for b in bands]; joinpath(dir, "tables", "meta.toml");
                                     [joinpath(dir, "assets", f) for f in figure_files(bands)]])
        for f in figure_files(bands)                                         # as in the paper: every line but the generator line, every pixel
            a = joinpath(dir, "assets", f); b = joinpath(expected, f)
            @test endswith(f, ".png") ? same_pixels(a, f) : endswith(f, "-caption.tex") ? read(a) == read(b) : same_text(a, b)
        end
        # the files name the driver's stage as their generator
        @test occursin("generated by experiments/scripts/texture_recovery.jl (stage bands", readline(joinpath(dir, "assets", "texture-learned.tex")))
        @test occursin("experiments/scripts/texture_recovery.jl (stage bands", readline(joinpath(dir, "tables", "meta.toml")))
        # the tables kept beside the figure: the record complete (the whole figure's numbers), the photograph's cut the input's
        V = TOML.parsefile(joinpath(dir, "tables", "meta.toml"))
        @test V["order"] == bands && V["photograph"]["number"] == 39 && haskey(V, "errors") && V["read_on"] === false
        @test read(joinpath(dir, "tables", "photograph.png")) == first(photograph_files()).second
        # an input of another content than the config pins is refused, and a data root without the band names what is missing
        other = collect(photograph_files()); other[1] = other[1].first => vcat(other[1].second, 0x00)
        e = withenv(() -> message(() -> call(:write_bands, t, mktempdir(); RECORDS...)), "VGTK_DATA_ROOT" => data_root(other))
        @test occursin("sha256", e) && occursin(t["photograph_cut"], e)
        e = withenv(() -> message(() -> call(:write_bands, t, mktempdir(); RECORDS...)), "VGTK_DATA_ROOT" => mktempdir())
        @test occursin(t["photograph_cut"], e) && occursin("provenance", e)
    end
