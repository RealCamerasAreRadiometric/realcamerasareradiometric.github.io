            e = check(c -> c["bands"]["ours"][k] = "");                      @test occursin("[bands].ours", e) && occursin(k, e)
        end
        e = check(c -> c["bands"]["ours"]["colour"] = "red");                @test occursin("[bands].ours", e) && occursin("colour", e)
        @test occursin("source", check(c -> c["bands"]["ours"]["source"] = "texture_learned"))                  # a blur model by its name, not its file
        @test occursin("source", check(c -> c["bands"]["ours"]["source"] = "pinhole"))                          # every band another source
