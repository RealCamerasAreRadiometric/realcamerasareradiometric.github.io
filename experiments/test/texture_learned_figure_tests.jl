        m = message(() -> tables_of(bands = [bands_of(["truth"])..., blur]))
        @test occursin("bands", m) && occursin("texture_blur.png", m)
        @test occursin("bands", message(() -> tables_of(bands = bands_of(["truth", "truth"]))))
        @test occursin("bands", message(() -> tables_of(bands = [bands_of(["truth"])..., merge(blur, (; source = "design"))])))
        @test occursin("evaluate, poses and roles", message(() -> generate(; part = "tables", data = mktempdir())))
        @test occursin("part", message(() -> generate(; part = "draw", data = tables, out = mktempdir())))
        # a selection without the photograph's band: three bands; the record still names the training photograph
        three = mktempdir(); selection = bands_of(["truth", "pinhole", "ours"])
        generate(; part = "all", data = joinpath(three, "tables"), out = joinpath(three, "figure"), RECORDS..., photograph = photograph_folder(), bands = selection)
        V3 = TOML.parsefile(joinpath(three, "tables", "meta.toml"))
        @test V3["order"] == ["truth", "pinhole", "ours"] && V3["photograph"]["number"] == 39 && !isfile(joinpath(three, "figure", "texture-learned", "photograph.tex"))
        @test sort(collect(keys(V3["errors"]))) == ["ours", "pinhole"]                # an error per band of a blur model
        @test count("\\input{\\rcfigdir/texture-learned/", read(joinpath(three, "figure", "texture-learned.tex"), String)) == 3
    end

    @testset "the bands' rows on a lined page: the same lines in every band, or reading on" begin
        # 13 text lines in the block: line l inks the block's rows 20 + 30 (l − 1) … 41 + 30 (l − 1), 8 white rows between two lines
        block = (100, 100, 727, 1065); x0, y0, x1, y1 = block
        lined = fill(0xff, 1169, 827)
        rows(n, read_on; lines_per_band = 3, white = 0.85) = G.texlearned_bands(lined, n, read_on; block, lines_per_band, white)
        for l in 1:13
            lined[(y0 + 20 + 30 * (l - 1) + 1):(y0 + 41 + 30 * (l - 1) + 1), (x0 + 1):x1] .= 0x20
        end
        # a cut lies in the middle of a gap (rows 42 … 49 after line 1: the cut after line 3 at 106); the first band begins half a gap above line 1
        @test rows(4, false) == (fill((16, 106), 4), 16)
        @test rows(4, true) == ([(16, 106), (106, 196), (196, 286), (286, 376)], 16)
        @test_throws ErrorException rows(5, true)                                     # 15 gaps needed, 12 between the 13 lines
        @test rows(5, false) == (fill((16, 106), 5), 16)
        @test rows(4, false; lines_per_band = 2) == (fill((16, 76), 4), 16)           # two lines per band: the cut after line 2 (its gap: rows 72 … 79)
        @test rows(6, true; lines_per_band = 2)[1][end] == (316, 376)
        lined[(y0 + 1):(y0 + 20), (x0 + 1):x1] .= 0xe0                                # a light grey above line 1 is not ink (0.88: lighter than 0.85 is white)
        @test rows(2, false) == (fill((16, 106), 2), 16)
        @test first(rows(2, false; white = 0.9)[1]) != (16, 106)                      # above a level of 0.9 it is: the rows are the first line's
        lined[y0 + 11, x0 + 300] = 0x00                                               # one dark texel is: the row is the first line's
        @test first(rows(2, false)[1]) != (16, 106)
    end
end

@testitem "texture-learned figure: the stage bands of the texture driver" default_imports = false setup = [TextureLearnedFigure] begin
    using Test
    using DrWatson
    using TOML: TOML
    using VisualGeometryToolkitEval.Experiments: run_isolated
    using .TextureLearnedFigure: FIXTURE, RECORDS, photograph_files, same_text, figure_files, same_pixels
    const SCRIPT = projectdir("scripts", "texture_recovery.jl")
    const CONFIG = projectdir("configs", "experiments", "texture_recovery_14mm_small.toml")
    "The driver's module on `config` (its plan only: nothing run) and what it printed."
    function driver(config = CONFIG)
        path, io = mktemp()
        m = try redirect_stdout(() -> run_isolated(SCRIPT; args = ["--plan", "--config=$config"]), io) finally close(io) end
        return m, read(path, String)
    end
    message(f) = try f(); "" catch err; sprint(showerror, err) end

    m, plan = driver()
    the(name) = Base.invokelatest(getglobal, m, name)                       # a global of the driver (defined in a newer world)
    call(name, args...; kw...) = Base.invokelatest(the(name), args...; kw...)
    cfg = the(:CFG); t = cfg["bands"]

    @testset "[bands] of the config of record; the stage, after the driver's own figures" begin
        @test t["order"] == ["truth", "photograph", "pinhole", "ours"] && t["read_on"] == "off" && t["asset_dir"] == "texture-learned"
        @test (t["block_mm"], t["lines_per_band"], t["white"], t["pixels_per_texel"]) == ([25.4, 25.4, 159.258, 245.11], 3, 0.85, 5)
        @test [t[b]["source"] for b in t["order"]] == ["design", "photograph", "pinhole", "learned"] && t["photograph"]["label"] == "training\\\\image"
        @test sort(collect(keys(t))) == sort([collect(the(:BANDS_KEYS)); t["order"]]) && all(b -> sort(collect(keys(t[b]))) == sort(collect(the(:BAND_KEYS))), t["order"])
        # the text block and the level of a blank row: those of the driver's own rendering of the same block of text
        @test all(k -> t[k] == cfg["figures"]["texture_stacked"][k], ("block_mm", "lines_per_band", "white"))
        stages = the(:STAGES)
        @test [s.name for s in stages][(end - 1):end] == [:figures, :bands]
        items = Base.invokelatest(stages[end].items)
        @test length(items) == 1 && items[1].key == call(:bands_product).key
        @test occursin(r"^\s+bands\s+0/1 produced"m, plan) && occursin("plan only", plan)
        @test :bands ∉ the(:GPU_STAGES)                                      # it draws on no device
    end

    @testset "the table checked when the config is loaded: a wrong key, band, setting, switch or input is refused" begin
