            endswith(f, ".tex") && !endswith(f, "-caption.tex") && @test same_text(joinpath(out, f), joinpath(expected, f))
        end
        # the checksums see one pixel: a band's image with one grey level more or less in one pixel is not the paper's
        changed = PaperFigures.load_grey_png(joinpath(out, "texture-learned", "ours.png")); changed[7, 11] ⊻= 0x01
        @test !same_pixels(PaperFigures.save_grey_png(joinpath(dir, "changed.png"), changed), "texture-learned/ours.png")
        # a band's image: its texels as they are, each 5 × 5 pixels
        up = T["pixels_per_texel"]
        @test up == 5 && PaperFigures.load_grey_png(joinpath(out, "texture-learned", "ours.png")) == repeat(PaperFigures.load_grey_png(joinpath(tables, "ours.png")); inner = (up, up))
        # another name and another magnification are the caller's: the files, the paths in them and the images follow
        other = joinpath(dir, "other")
        generate(; data = tables, out = other, asset_dir = "strip", pixels_per_texel = 2)
        @test sort(readdir(other)) == ["strip", "strip-caption.tex", "strip.tex"] && sort(readdir(joinpath(other, "strip"))) == sort(["$b.$e" for b in BANDS for e in ("png", "tex")])
        @test count("\\input{\\rcfigdir/strip/", read(joinpath(other, "strip.tex"), String)) == 4 && occursin("{\\rcfigdir/strip/ours.png}", read(joinpath(other, "strip", "ours.tex"), String))
        @test PaperFigures.load_grey_png(joinpath(other, "strip", "ours.png")) == repeat(PaperFigures.load_grey_png(joinpath(tables, "ours.png")); inner = (2, 2))
        @test read(joinpath(other, "strip-caption.tex")) == read(joinpath(expected, "texture-learned-caption.tex"))
        # the generator line names what the caller says wrote the files (a driver's stage names itself); nothing else changes
        named = joinpath(dir, "named")
        generate(; data = tables, out = named, generator = "a driver (its stage)")
        @test all(f -> startswith(readline(joinpath(named, f)), "% $f — generated by a driver (its stage); do not edit."), filter(endswith(".tex"), figure_files(BANDS)[1:end-1]))
        @test all(f -> same_text(joinpath(named, f), joinpath(expected, f)), filter(endswith(".tex"), figure_files(BANDS)[1:end-1]))
