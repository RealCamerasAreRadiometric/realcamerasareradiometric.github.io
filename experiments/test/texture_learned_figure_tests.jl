        short = joinpath(mktempdir(), "page.json"); write(short, JSON.json(Dict("photographs" => page["photographs"][2:end], "roles" => page["roles"][2:end])))
        @test occursin("differ", message(() -> tables_of(records = merge(RECORDS, (; roles = short)))))
        # a band cut for other text lines than the layout's, or not of the size its record states
        @test occursin("other text lines", message(() -> tables_of(photograph = photograph_folder(edit = t -> replace(t, "lines = [1, 3]" => "lines = [4, 6]")))))
        @test occursin("not of the size", message(() -> tables_of(photograph = photograph_folder(edit = t -> replace(t, "pixels = [573, 76]" => "pixels = [573, 77]")))))
        # the bands: each name and each source once, a blur model one of the run's; the parts: tables need the run's records, the figure a folder
