# =============================================================================
# src/convergence_panels.jl — the paper's convergence figure (fig:convergence-rms, src/fig/convergence-rms.tex and its panels
# convergence-rms/<case>.tex, <case>-narrow.tex): per case, the median per LM iteration of the detections' true reprojection error
# (|proj(X; camera_it, pose_it) − detection| in px over the start's detections every iteration projects) and of the held-out Thorlabs
# error (the chrome evaluation's motion fit, held out), on one axis. The PGFPlots text is T. Harder's rms_figure.py's style, option for
# option (the paper's files); only the data-dependent parts are computed: the title, the detections' colour, the x
# range, the y range (rms_figure.py's linear rule) and the two coordinate lists (6 significant digits). Plain string code: no package.
# =============================================================================
import Printf

"The colour of a panel's detections curve and key entry, by its target (the key's colours: AprilGrid red, Siemens stars green)."
const CONVERGENCE_PANEL_COLOURS = Dict("aprilgrid" => "FF0000", "siemens" => "228833")

"A number at 6 significant digits as Python's `%.6g` prints it (rms_figure.py's coordinates): trailing zeros dropped."
function g6(x::Real)
    s = Printf.@sprintf("%.6g", x)
    occursin('e', s) || return s
    m, e = split(s, 'e')                                     # %g's exponent: two digits at least, its sign kept (Python's form)
    return m * "e" * (e[1] in "+-" ? e[1] : '+') * lpad(lstrip(e, ['+', '-']), 2, '0')
end
"A number as Python's `%g` prints it (the y range's ends and step)."
gshort(x::Real) = Printf.@sprintf("%g", x)

"The coordinate list `(x,y) …` of the iterations `xs` and the values `ys`."
panel_coordinates(xs, ys) = join(("($x,$(g6(y)))" for (x, y) in zip(xs, ys)), " ")

"""
    panel_yaxis(values) -> String

rms_figure.py's linear y range: the 1-2-5 tick distance that gives at most five intervals between the lowest and the highest value, from the
tick at or below the lowest to the tick at or above the highest — `ymin=…, ymax=…, ytick distance=…`.
"""
function panel_yaxis(vals)
    lo, hi = extrema(vals)
    tick = first(q for e in -6:6 for m in (1, 2, 5) for q in (m * 10.0^e,) if (hi - lo) / q <= 5)
    y0 = floor(lo / tick + 1e-9) * tick; y1 = ceil(hi / tick - 1e-9) * tick
    return "ymin=$(gshort(y0)), ymax=$(gshort(y1)), ytick distance=$(gshort(tick))"
end

"""
    convergence_panel_tex(case, title, target, iterations, detections, heldout; narrow) -> String

One panel of the convergence figure (`narrow`: the one-column rendering, the title on two lines, fewer x ticks): the text of
rms_figure.py's panel with this case's title, colour, ranges and curves.
"""
function convergence_panel_tex(case::AbstractString, title::AbstractString, target::AbstractString, iterations, detections, heldout; narrow::Bool)
    col = CONVERGENCE_PANEL_COLOURS[target]
    xmax = last(iterations); ya = panel_yaxis([detections; heldout])
    chr = panel_coordinates(iterations, heldout); det = panel_coordinates(iterations, detections)
    head = "% convergence-rms/$case$(narrow ? "-narrow" : "").tex — generated by experiments/scripts/convergence.jl (stage panels; the style of convergence/tools/rms_figure.py); do not edit.\n"
    if narrow
        t2 = replace(title, ", " => ",\\\\"; count = 1)
        return head * """
% The panel $case.tex for a narrow place (two panels beside each other in one column): the same curves, the title on two lines,
% the key's entries under each other, fewer x ticks. The axis box is \\rcpanelwidth wide and is all of the picture's width.
\\providecommand{\\rcpanelwidth}{\\linewidth}\\providecommand{\\rcpanelylabel}{Median error [px]}%
\\definecolor{rcdet}{HTML}{$col}\\definecolor{rcchr}{HTML}{0000FF}%
\\begin{tikzpicture}[baseline=(current bounding box.south), trim axis left, trim axis right]
\\begin{axis}[width=\\rcpanelwidth, height=0.58*\\rcpanelwidth, scale only axis, xmin=0, xmax=$xmax, xtick distance=$(xmax <= 15 ? 5 : 10), $ya, tick label style={font=\\scriptsize}, label style={font=\\scriptsize}, tick align=outside, tick style={black!60, line width=0.3pt}, axis line style={black!60, line width=0.3pt}, scaled y ticks=false, title style={font=\\scriptsize, align=center, yshift=-4pt}, title={$t2}, xlabel={LM iteration}, xtick pos=left, ytick pos=left, ymajorgrids, grid style={black!12, line width=0.3pt}, clip=false, yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2}, ylabel={\\rcpanelylabel}, ylabel style={yshift=-2pt}, xlabel style={yshift=2pt}]
\\addplot[rcchr, line width=0.9pt, no marks] coordinates {$chr};
\\addplot[rcdet, line width=0.9pt, no marks] coordinates {$det};
\\end{axis}
% the key: two lines under the axis box, centred on it; overlay (it may be wider than the box), its height kept by the path
\\path ([yshift=-0.40in]current axis.south) -- ++(0pt,-1.9ex);
\\end{tikzpicture}%
"""
    end
    return head * """
% One panel ($title): the median per LM iteration of the detections' true reprojection error and of the held-out reprojection error on
% the high-precision target, both in px on one axis, its key under it. The axis box is \\rcpanelwidth wide (\\linewidth when the host
% does not define it) and is ALL of the picture's width (trim axis left / right): the y tick labels and the y label \\rcpanelylabel
% stand out to its left, the last x tick label to its right — the host leaves room for them. The baseline is the picture's lower edge.
\\providecommand{\\rcpanelwidth}{\\linewidth}\\providecommand{\\rcpanelylabel}{Median reprojection error [px]}%
\\definecolor{rcdet}{HTML}{$col}\\definecolor{rcchr}{HTML}{0000FF}%
\\begin{tikzpicture}[baseline=(current bounding box.south), trim axis left, trim axis right]
\\begin{axis}[width=\\rcpanelwidth, height=0.4259*\\rcpanelwidth, scale only axis, xmin=0, xmax=$xmax, $ya, tick label style={font=\\scriptsize}, label style={font=\\scriptsize}, tick align=outside, tick style={black!60, line width=0.3pt}, axis line style={black!60, line width=0.3pt}, scaled y ticks=false, title style={font=\\footnotesize, yshift=-3pt}, title={$title}, xlabel={LM iteration}, xtick pos=left, ytick pos=left, ymajorgrids, grid style={black!12, line width=0.3pt}, clip=false, yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2}, ylabel={\\rcpanelylabel}]
\\addplot[rcchr, line width=0.9pt, no marks] coordinates {$chr};
\\addplot[rcdet, line width=0.9pt, no marks] coordinates {$det};
\\end{axis}
% the key: centred under the axis box; it may be wider than the box, so it does not count for the picture's width (overlay) —
% the short invisible path keeps its height in the picture's bounding box
\\path ([yshift=-0.5in-0.9ex]current axis.south) -- ++(0pt,2ex);
\\end{tikzpicture}%
"""
end

