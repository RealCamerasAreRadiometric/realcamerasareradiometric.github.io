# =============================================================================
# src/paper_figures/teaser.jl — the paper's teaser figure (fig:teaser: src/fig/teaser.tex, its panels teaser/<panel>.{png,tex} and
# teaser/texture-strip.{png,tex}, and teaser-caption.tex). The port of T. Harder's teaser.py (the figure folder's tools/), part for
# part. The figure is made of two other figures' pieces:
#
#   row 1   the same part of one panorama, once per panel — in the paper two: composed from the frames as they are and from the
#           frames with our learned vignetting divided out —, side by side, each with its title on plain white at its upper edge.
#           The panels' images are the caller's (a stage's crops of the panorama stage's panoramas); they are copied as they are.
#   row 2   ONE strip of the first text lines of the printed page, cut into equal parts from left to right, each part from
#           another band of the learned-texture figure's tables (<band>.png), joined by hard cuts — the text reads on across them.
#           Every part is on the page's texel grid, one texel drawn as a square of pixels without interpolation. A band that is not
#           on that grid (the training photograph's cut: its own pixels, turned level) is scaled to it with Pillow's Lanczos filter,
#           as teaser.py scaled it. The parts' names stand under the strip, text of the host document.
#
# What the figure shows is the caller's — a driver's config of record (scripts/teaser.jl, `[teaser]`): the figure's name, the
# panels and their titles, the factor they were brightened by, the lens the caption names, the strip's parts with their names and
# the caption's words for them, the pixels a texel is drawn with. This file states none of them.
#
# Pillow's Lanczos resize, the PNG files and the panel that shows an image are common.jl's (pillow_resize_lanczos, load_png,
# load_grey_png, save_grey_png, image_panel).
# =============================================================================

"""
    teaser_grey(img) -> Matrix{UInt8}

An 8-bit image (h × w × 3) as grey, as Pillow's `convert("L")` gives it: a grey image stays as it is, a colour becomes its
ITU-R 601-2 luma (0.299 R + 0.587 G + 0.114 B in Pillow's 16-bit integer weights, rounded half up).
"""
teaser_grey(img::AbstractArray{UInt8, 3}) =
    [((19595 * Int(img[j, i, 1]) + 38470 * Int(img[j, i, 2]) + 7471 * Int(img[j, i, 3]) + 0x8000) >> 16) % UInt8 for j in axes(img, 1), i in axes(img, 2)]

"""
    figure_teaser(; crops, texture, out, generator, asset_dir, panels, gain, lens, segments, texel_grid, pixels_per_texel) -> Vector{String}

Draws the teaser into the folder `out`: <asset_dir>.tex, <asset_dir>/ (the images and their PGFPlots panels) and
<asset_dir>-caption.tex. Returns the files written.

- `crops`: the folder with the images of row 1, `<panel>.png` per panel (all of one size);
- `texture`: the learned-texture figure's tables (`<band>.png` per part of the strip);
- `generator`: what the written files name as their generator (by default this file; the stage `teaser` of scripts/teaser.jl
  names itself).

The settings are required, the stage hands them from its config of record:
- `asset_dir`: the figure's name — its file, the folder of its panels and its caption's file (`[teaser] asset_dir`);
- `panels`: the panels of row 1 from the left, each `(; panel, title)` — its files' name and its title (`[teaser] panels`); the
  caption is written for two: the frames as they are, then the frames with our learned vignetting divided out;
- `gain`: the factor the panels' images were brightened by, which the caption states (1: not brightened; `[teaser] gain`);
- `lens`: the lens of the panorama as the caption names it, LaTeX (`[teaser] lens`);
- `segments`: the strip's parts from the left, each `(; name, label, caption)` — the band of the texture tables it comes from, its
  name under the strip and the caption's words for it (`[teaser] segments` and `[teaser.<segment>]`);
- `texel_grid`: the band of the texture tables whose image is on the page's texel grid, one pixel per texel: the strip's size
  (`[teaser] texel_grid`);
- `pixels_per_texel`: a texel of the strip is drawn as a square of this many pixels, not interpolated (`[teaser] pixels_per_texel`).
"""
function figure_teaser(; crops::AbstractString, texture::AbstractString, out::AbstractString, generator::AbstractString = "experiments/src/paper_figures/teaser.jl",
                       asset_dir::AbstractString, panels, gain::Real, lens::AbstractString, segments, texel_grid::AbstractString, pixels_per_texel::Integer)
    NAME = asset_dir; GEN = "generated by $generator; do not edit"; UP = pixels_per_texel
    COLGAP, ROWGAP, LABELGAP = 4, 7, 2.5     # pt: between the two panorama panels; between the rows; between the strip and the parts' names under it
    order = [String(s.name) for s in segments]
    (!isempty(order) && allunique(order)) || error("segments: the strip's parts, each band once")
    length(panels) == 2 || error("panels: two — the frames as they are, and the frames with the learned vignetting divided out (the caption is written for them)")
    gain > 0 || error("gain must be positive")
    written = String[]
    mkpath(joinpath(out, NAME))

    # ---- row 1: the panorama's part, once per panel, as the images are
    sizes = Set{Tuple{Int, Int}}()
    for p in panels
        src = joinpath(crops, p.panel * ".png"); isfile(src) || error("no $src")
        dst = joinpath(out, NAME, p.panel * ".png"); write(dst, read(src)); push!(written, dst)   # the file itself (written, not copied: a source may be read-only)
        h, w = size(load_png(src))[1:2]; push!(sizes, (w, h))
    end
    length(sizes) == 1 || error("the two panorama panels differ in size: $sizes")
    PW, PH = only(sizes)
    for p in panels
        push!(written, image_panel(joinpath(out, NAME, p.panel * ".tex"),
            "% $NAME/$(p.panel).tex — $GEN.\n% Row 1: the panorama crop, $(p.title) ($PW x $PH px, the panel of the panorama-crop figure as it is).", NAME, p.panel * ".png", PW, PH))
    end

    # ---- row 2: the strip of the page's first text lines, its parts from left to right
    H, W = size(load_grey_png(joinpath(texture, texel_grid * ".png")))
    n = length(order); cuts = [round(Int, k * W / n) for k in 0:n]                   # the parts' texel columns (halves to the even number, as Python rounds)
    parts = map(enumerate(order)) do (k, s)
        im = teaser_grey(load_png(joinpath(texture, s * ".png")))
        size(im) == (H, W) || (im = pillow_resize_lanczos(reshape(im, size(im)..., 1), W, H)[:, :, 1])   # a band of its own pixels onto the page's texel grid
        im[:, cuts[k]+1:cuts[k+1]]
    end
    strip = reduce(hcat, parts); size(strip) == (H, W) || error("the strip is $(size(strip, 2)) x $(size(strip, 1)) texels, not $W x $H")
    push!(written, save_grey_png(joinpath(out, NAME, "texture-strip.png"), repeat(strip; inner = (UP, UP))))
    cutlist(c) = "[" * join(c, ", ") * "]"                                           # a list of integers as Python prints it
    push!(written, image_panel(joinpath(out, NAME, "texture-strip.tex"),
        "% $NAME/texture-strip.tex — $GEN.\n% Row 2: the first three text lines of the page ($W x $H texels, $UP x $UP px each), cut at the texel columns $(cutlist(cuts[2:end-1])): " *
        join(("$(s.label) $(cuts[k]) … $(cuts[k+1])" for (k, s) in enumerate(segments)), ", ") * ".", NAME, "texture-strip.png", W, H))

    # ---- the composition
    # a title on plain white, lying 1.5 pt below a panel's upper edge
    headbox(text) = "\\raisebox{\\dimexpr0.5\\rcpanelht-1.5pt\\relax}[0pt][0pt]{\\tikz[baseline=(k.north)]\\node[fill=white,inner sep=1.2pt,font=\\scriptsize](k){$text};}"
    head(label) = "\\makebox[0pt][r]{\\makebox[\\rcpanelwd][c]{$(headbox(label))}}"
    names = join("\\makebox[$(cuts[k+1] - cuts[k])\\dimexpr\\rcteaserwd/$W\\relax][c]{\\scriptsize $(s.label)}" for (k, s) in enumerate(segments))
    push!(written, write_lines(joinpath(out, NAME * ".tex"), [
        "% $NAME.tex — $GEN.",
        "% The teaser: row 1 the panorama crop without and with our vignetting correction (two PGFPlots pictures, $NAME/pano-*.tex, each with",
        "% its label on plain white); row 2 one strip of the page's first three text lines whose parts, from left to right, come from the",
        "% sources named under them, joined by hard cuts ($NAME/texture-strip.tex). All names are LaTeX text in the host document's fonts.",
        "% \\input it at text width (figure*); it needs pgfplots (compat 1.18). \\rcfigdir is the folder this file lies in (default src/fig).",
        "\\providecommand{\\rcfigdir}{src/fig}%",
        "\\begingroup",
        "\\ifdefined\\rcpanelwd\\else\\newlength\\rcpanelwd\\fi\\ifdefined\\rcpanelht\\else\\newlength\\rcpanelht\\fi\\ifdefined\\rcteaserwd\\else\\newlength\\rcteaserwd\\fi",
        "\\setlength{\\rcteaserwd}{\\linewidth}\\setlength{\\rcpanelwd}{\\dimexpr(\\linewidth-$(COLGAP)pt)/2\\relax}\\setlength{\\rcpanelht}{$(fixed(PH / PW, 5))\\rcpanelwd}%",
        "\\footnotesize\\setlength{\\tabcolsep}{0pt}\\renewcommand{\\arraystretch}{1}%",
        "\\begin{tabular}{@{}l@{}}",
        "  {\\def\\rcpanelwidth{\\rcpanelwd}%",
        # \noalign: the panels are deeper than a strut, so \\[..] would add nothing
        "   " * join(("\\input{\\rcfigdir/$NAME/$(p.panel)}$(head(p.title))" for p in panels), "\\hspace{$(COLGAP)pt}") * "} \\\\\\noalign{\\vskip $(pystr(ROWGAP))pt}",
        "  {\\def\\rcpanelwidth{\\rcteaserwd}\\input{\\rcfigdir/$NAME/texture-strip}} \\\\\\noalign{\\vskip $(pystr(LABELGAP))pt}",   # the names under the strip
        "  $names \\\\",
        "\\end{tabular}%", "\\endgroup"]))

    # the caption states the factor the panels were brightened by
    words = [String(s.caption) for s in segments]
    push!(written, write_lines(joinpath(out, NAME * "-caption.tex"), [
        "Top: a part of a panorama of one pure-rotation sweep ($lens), composed from the frames as they are and from " *
        "the frames with our learned vignetting divided out; without the correction the vignetting shows as brightness steps over the windows" *
        (gain == 1 ? "" : " (both panels brightened by the same factor $(general(gain, 6)) for display)") * ". " *
        "Bottom: the first three lines of a printed page of text, from left to right " *
        (length(words) > 1 ? join(words[1:end-1], ", ") * ", and " * words[end] : words[1]) * "; the parts are joined by hard cuts."]))
    return written
end

FIGURES["teaser"] = figure_teaser
