# vignetting.jl — the paper's vignetting figure (fig:vignetting: src/fig/vignetting.tex, its panels vignetting/<lens>-diagonal.tex
# and vignetting-caption.tex) as PGFPlots / TikZ; the port of the figure folder's tools/vignetting.py: its `figure` step with the
# one row of panels the paper shows, `diagonal` (the Python's other rows are not here). Every panel is its own PGFPlots picture; a
# LaTeX tabular puts them side by side, and its titles, axis names and legend are text of the host document.
#
#   PaperFigures.generate("vignetting"; data = <tables>, out = <dir>, asset_dir, panels, caption_labels, samples)
#
# The settings are the caller's (the stage `figures` of scripts/vignetting_figure.jl hands them from its config of record): the
# figure's name, each lens's panel file and its name in the caption, the number of samples a curve is drawn through. Nothing here
# names a lens.
#
# One panel per lens: V / V(𝔠) along the sensor's diagonal through the centre 𝔠 of the learned profile — the diffuser's flat field,
# the learned vignetting and the thin lens model's cos⁴α (tan α = distance from 𝔠 / focal length) over the position along the
# diagonal (px from 𝔠).
#
# The curves have no markers: the thin lens model red, the flat field a darker green (the full green is hard to see on white), the
# learned vignetting blue, dashed and drawn last, so that it lies on top and the other two show through its gaps. The legend is one
# line under the figure. The caption states what the panels show and the agreement of the learned vignetting with the flat field
# (median, mean and RMS of |ln(V_ours / V_flat)| along the diagonal, per lens).
#
# Reads from <tables>:
#   meta.toml              diagonal_ymax (the upper y limit), order (the lenses, left to right) and per lens [lenses.<lens>]:
#                          label, t_min, t_max (the ends of the diagonal, px)
#   <lens>_diagonal.tsv    t flat learned cos4: the position along the diagonal (px from 𝔠) and the three curves, each over its
#                          value at 𝔠; one header line
#
# The numbers are computed in the order NumPy computed them (common.jl npsum for the sums and means), so that the files come out the same.
# Julia's logarithm differs from NumPy's in the last bits (about 1e-16 in a value); a printed digit differs only where a value lies
# that close to a rounding tie.

"The mean of `a`, its sum taken in NumPy's order (common.jl npsum)."
vig_mean(a) = npsum(a) / length(a)
"Median, mean and RMS of |v|."
vig_stats(v) = (a = abs.(v); (; median = Statistics.median(a), mean = vig_mean(a), rms = sqrt(vig_mean(a .^ 2))))

"A table of numbers with one header line: a matrix, one row per line."
function vig_table(path::AbstractString)
    rows = [parse.(Float64, split(l)) for l in Iterators.drop(eachline(path), 1) if !isempty(strip(l))]
    return permutedims(reduce(hcat, rows))
end
"The coordinate list `(x,y) …` of a curve (x at 6 significant digits, y at 4 decimals); a sample that is not finite is left out."
vig_coords(xs, ys) = join(("(" * general(x, 6) * "," * fixed(y, 4) * ")" for (x, y) in zip(xs, ys) if isfinite(x) && isfinite(y)), " ")
"The indices of at most about `most` of `n` samples, evenly spaced, the first and the last among them."
function vig_thin(n::Integer, most::Integer)
    k = collect(1:max(1, cld(n, most)):n)
    return k[end] == n ? k : [k; n]
end
"A lens's name as the two parts of a column title: \"Sigma 14 mm lens, f/4\" gives (\"Sigma 14\\,mm lens\", \"\$f/4\$\")."
function vig_fnum(label::AbstractString)
    a, b = split(label, ", ")
    return replace(a, " mm" => "\\,mm"), "\$f/" * split(b, "/")[2] * "\$"
end
"Round ticks about 0: the multiples of the largest of `spacings` whose outermost tick stays within `frac` of the range."
function vig_nice_ticks(lo::Real, hi::Real, spacings, frac::Real)
    m = max(abs(lo), abs(hi)); fit = [q for q in spacings if q <= frac * m]; s = isempty(fit) ? first(spacings) : maximum(fit)
    return [k * s for k in ceil(Int, lo / s):floor(Int, hi / s) if abs(k * s) <= frac * m + 1e-9]
end

"""
    vig_panel(out, rel, about, axis, plots; generator) -> path

Writes one panel, the file `rel` under `out`: a PGFPlots axis with the options `axis` behind the shared ones and the lines `plots`
inside; `about` is what the comment at the top says about it, `generator` what its first line names as the file's generator.
"""
vig_panel(out, rel, about, axis, plots; generator::AbstractString) = write_lines(joinpath(out, rel), [
    "% $rel — generated by $generator; do not edit."; ["% " * l for l in about];
    "% Its width is \\rcpanelwidth (\\linewidth when the host does not define it); the baseline is the axis' centre, the picture is its axis box.";
    "\\providecommand{\\rcpanelwidth}{\\linewidth}%";
    "\\begin{tikzpicture}[baseline=(current axis.center), trim axis left, trim axis right]";
    # the curves' colours: the full blue, a darker green (00FF00 was hard to see on white), the full red
    "\\definecolor{rcvlearned}{HTML}{0000FF}\\definecolor{rcvflat}{HTML}{00A000}\\definecolor{rcvthin}{HTML}{FF0000}";
    # a panel is 0.74 of its width high
    "\\begin{axis}["; "  scale only axis, width=\\rcpanelwidth, height=0.74*\\rcpanelwidth,"; "  " * HOUSE_AXIS_COMMON * ",";
    # the axis options every panel shares, behind the house style
    "  axis x line*=bottom, axis y line*=left, axis line style={line width=0.4pt}, tick align=outside, tick style={black, line width=0.3pt},\n" *
    "  major tick length=2pt, scaled ticks=false, /pgf/number format/1000 sep={}, enlargelimits=false,\n" * "  " * axis * "]";
    plots; "\\end{axis}"; "\\end{tikzpicture}%"])

"""
    figure_vignetting(; data, out, generator, asset_dir, panels, caption_labels, samples) -> Vector{String}

Draws the vignetting figure from the tables in `data` into `out`: <asset_dir>.tex, <asset_dir>/<panel>-diagonal.tex per lens and
<asset_dir>-caption.tex. Prints the numbers behind the caption. Returns the files written.

`generator`: what the written files name as their generator (by default this file; the stage `figures` of
scripts/vignetting_figure.jl names itself). The settings are required, the stage hands them from its config of record:
- `asset_dir`: the figure's name — its file, the folder of its panels and its caption's file (`[figure] asset_dir`);
- `panels`: per lens of the tables the name of its panel's file (`[lenses.<lens>] panel`);
- `caption_labels`: per lens of the tables its name inside the caption's sentence (`[lenses.<lens>] caption_label`);
- `samples`: about how many of a diagonal's samples a curve is drawn through (`[figure] samples`).
"""
function figure_vignetting(; data::AbstractString, out::AbstractString, generator::AbstractString = "experiments/src/paper_figures/vignetting.jl",
                           asset_dir::AbstractString, panels::AbstractDict, caption_labels::AbstractDict, samples::Integer)
    f0(v) = fixed(v, 0); f3(v) = fixed(v, 3); f4(v) = fixed(v, 4); g(v) = general(v, 6)
    V = TOML.parsefile(joinpath(data, "meta.toml")); ymax = V["diagonal_ymax"]
    lenses = Tuple{String, String}[]; facts = NamedTuple[]; written = String[]
    # the curves' line styles, in the panels and in the legend: no markers; the learned vignetting dashed and drawn last, so that it
    # lies on top and the other two show through its gaps
    learned_line = "rcvlearned, line width=1pt, dash pattern=on 3pt off 1.5pt"; flat_line = "rcvflat, line width=1pt"; thin_line = "rcvthin, line width=1pt"
    for k in V["order"]
        haskey(panels, k) && haskey(caption_labels, k) || error("figure_vignetting: the lens $k of $data has no panel or no caption label")
        L = V["lenses"][k]; label = L["label"]; slug = panels[k]; push!(lenses, (slug, label)); xlo = L["t_min"]; xhi = L["t_max"]
        xaxis = "xmin=$(f0(xlo)), xmax=$(f0(xhi)), xtick={" * join((g(q) for q in vig_nice_ticks(xlo, xhi, (100, 200, 250, 500, 1000, 2000, 2500, 5000), 0.8)), ",") * "}"
        D = vig_table(joinpath(data, "$(k)_diagonal.tsv")); T = D[:, 1]; flat = D[:, 2]; learned = D[:, 3]; cos4 = D[:, 4]
        i = vig_thin(length(T), samples); t = T[i]        # the samples drawn: about `samples` of them
        push!(written, vig_panel(out, "$asset_dir/$slug-diagonal.tex",
            ["One panel ($label): the vignetting along the sensor's diagonal through the centre of the learned profile (px from it), every",
             "curve over its value there: the thin lens model's cos^4 alpha (red), the diffuser's flat field (green), the learned vignetting (blue, dashed, on top)."],
            "$xaxis, ymin=0, ymax=$(g(ymax)), ytick={0,0.5,1}",
            ["\\addplot[$thin_line] coordinates {$(vig_coords(t, cos4[i]))};", "\\addplot[$flat_line] coordinates {$(vig_coords(t, flat[i]))};",
             "\\addplot[$learned_line] coordinates {$(vig_coords(t, learned[i]))};"]; generator))
        # the agreement the caption states: ln(learned / flat field) at every sample of the diagonal, undefined where one of them is not positive
        q = [(flat[j] > 0 && learned[j] > 0) ? log(learned[j] / flat[j]) : NaN for j in eachindex(T)]
        push!(facts, (; label, caption_label = caption_labels[k], vig_stats(filter(isfinite, q))...))
    end

    # the composition: titles, the row's name, the axis name and the legend are text of the host document
    noy = "\\pgfplotsset{every axis/.append style={yticklabels=\\empty}}"   # the y axis' numbers: the first panel's
    rowlabel(s) = "\\smash{\\raisebox{-0.5\\height}{\\rotatebox{90}{$s}}}"  # smashed: a name longer than a panel is high does not open the row
    vo = "V_{\\mathrm{ours}}"; vf = "V_{\\mathrm{flat}}"
    row = join(((j == 1 ? "" : noy) * "\\input{\\rcfigdir/$asset_dir/$s-diagonal}" for (j, (s, _)) in enumerate(lenses)), " &\n  ")
    sample(st) = "\\tikz[baseline=-0.6ex]{\\draw[$st] (0,0) -- (12pt,0);}"
    legend = join(("\\mbox{$(sample(st))\\,$txt}" for (st, txt) in ((flat_line, "flat field"), (learned_line, "learned (ours)"),
                   (thin_line, "thin lens model (\$\\cos^4\\alpha\$)"))), "\\enspace ")
    gapl, gapc, gapr = 24, 7, 4                               # pt: left of the first panel (its y numbers, clear of the row's name), between the panels, right of the last (the last x number)
    title(l) = (p = vig_fnum(l); "\\makebox[0pt]{\\scriptsize\\begin{tabular}[b]{@{}c@{}}" * p[1] * "\\\\" * p[2] * "\\end{tabular}}")
    push!(written, write_lines(joinpath(out, "$asset_dir.tex"), [
        "% $asset_dir.tex — generated by $generator; do not edit.";
        "% The figure: its 3 panels (one PGFPlots picture each, $asset_dir/*.tex) stacked in a tabular; the panels of a lens share the x axis.";
        "% The column titles, the row names, the axis name and the legend are LaTeX text in the host document's fonts. \\input it inside a";
        "% figure; it needs \\usepackage{pgfplots} (which loads graphicx), \\pgfplotsset{compat=1.18} and amssymb. \\rcfigdir is the folder this file lies in, as the";
        "% host document sees it (default src/fig).";
        "\\providecommand{\\rcfigdir}{src/fig}%";
        "\\begingroup";
        "\\ifdefined\\rcpanelwd\\else\\newlength\\rcpanelwd\\fi";
        "\\setlength{\\rcpanelwd}{\\dimexpr(\\linewidth-$(10 + gapl + 2 * gapc + gapr)pt)/3\\relax}\\def\\rcpanelwidth{\\rcpanelwd}%";
        # the curves' colours, for the legend: the full blue, a darker green (00FF00 was hard to see on white), the full red
        "\\definecolor{rcvlearned}{HTML}{0000FF}\\definecolor{rcvflat}{HTML}{00A000}\\definecolor{rcvthin}{HTML}{FF0000}%";
        "\\footnotesize\\setlength{\\tabcolsep}{0pt}%";
        "\\begin{tabular}{@{}c@{\\hspace{$(gapl)pt}}c@{\\hspace{$(gapc)pt}}c@{\\hspace{$(gapc)pt}}c@{\\hspace{$(gapr)pt}}}";
        "  & " * join((title(l) for (_, l) in lenses), " & ") * " \\\\[2pt]";
        "  " * rowlabel("\$V / V(\\mathfrak{c})\$") * " &\n  " * row * " \\\\\\noalign{\\vskip 1pt}";
        "  & \\multicolumn{3}{@{}c@{\\hspace{$(gapr)pt}}}{position along the diagonal [px]} \\\\\\noalign{\\vskip 5pt}";
        "  % the legend: one line, shrunk only when it is wider than the line";
        "  \\multicolumn{4}{@{}c@{}}{\\resizebox{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}{!}{" * legend * "}} \\\\";
        "\\end{tabular}%"; "\\endgroup"]))

    # the caption: what the panels show, and the agreement of the learned vignetting with the flat field per lens
    agree = "median, mean and RMS of \$|\\ln($vo / $vf)|\$ along the diagonal: " *
            join(("$(join(vig_fnum(F.caption_label), ", ")): $(f3(F.median)), $(f3(F.mean)), $(f3(F.rms))" for F in facts), "; ")
    push!(written, write_lines(joinpath(out, "$asset_dir-caption.tex"), [
        "Vignetting of the three lenses over the sensor's diagonal through the centre \$\\mathfrak{c}\$ of the learned profile, " *
        "every curve divided by its value at \$\\mathfrak{c}\$: the flat field of a diffuser photograph, the vignetting our refinement learned, " *
        "and the thin lens model's \$\\cos^4\\alpha\$. The learned vignetting, written \$$vo\$, agrees with the flat field \$$vf\$ to ($agree)."]))

    # the numbers behind the caption, at one more digit
    println("-> $out/$asset_dir.tex + $asset_dir/ ($(length(lenses)) lenses)")
    for F in facts
        println("   $(F.label): |ln(learned / flat field)| along the diagonal: median $(f4(F.median)), mean $(f4(F.mean)), RMS $(f4(F.rms))")
    end
    return written
end

FIGURES["vignetting"] = figure_vignetting
