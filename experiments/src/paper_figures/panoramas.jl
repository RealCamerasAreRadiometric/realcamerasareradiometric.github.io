# =============================================================================
# src/paper_figures/panoramas.jl — the supplement's panoramas figure (src/fig/panoramas-james.tex, its panels
# panoramas-james/<lens>-<column>.{png,tex} and panoramas-james-caption.tex). The port of T. Harder's panorama_pgf.py (the figure
# folder's tools/), part for part; every number is printed as Python printed it.
#
# One row per lens, one column per candidate vignetting of the panorama stage (scripts/panorama_stitching.jl, stage panoramas:
# panorama_<candidate>.png) — in the paper two: the panorama composed from the frames as they are, and the same frames with our
# learned vignetting divided out. Every panel is its own PGFPlots picture and every label is LaTeX text of the host document. Each
# panorama goes through one display curve and is then reduced to the panels' width with Pillow's Lanczos filter (common.jl
# pillow_resize_lanczos); both are done as NumPy and Pillow do them, so that the images come out the same, pixel for pixel.
#
# What the figure shows is the caller's — a driver's config of record (scripts/panorama_figure.jl, `[figure]` and `[lenses]`): the
# figure's name, the lenses and their names, the columns and their titles, the display curve, the panels' width. This file states
# none of them.
# =============================================================================

# ---- the display curve ----------------------------------------------------------------------------------------------------------

"""
    panorama_display_table(gain, gamma) -> Vector{UInt8}

The display curve for the 256 values of an 8-bit channel, back to 8 bit (entry v + 1 for the value v): with x = v / 255 the curve is
g x / (1 + (g − 1) x), then its power 1 / gamma. Computed in single precision in NumPy's order of operations, as panorama_pgf.py
did on the whole image, and rounded half to even.
"""
function panorama_display_table(gain::Real, gamma::Real)
    g = Float32(gain); g1 = Float32(Float64(gain) - 1); p = Float32(1 / Float64(gamma))
    return [(x = Float32(v) / 255.0f0; UInt8(clamp(round(255.0f0 * (g * x / (1.0f0 + g1 * x))^p), 0.0f0, 255.0f0))) for v in 0:255]
end

# ---- the figure -----------------------------------------------------------------------------------------------------------------

"""
    figure_panoramas(; panoramas, out, generator, asset_dir, order, panels, labels, apertures, columns, gain, gamma, width) -> Vector{String}

Draws the panoramas figure into the folder `out`: <asset_dir>.tex, <asset_dir>/<panel>-<column>.{png,tex} and
<asset_dir>-caption.tex. Returns the files written.

- `panoramas`: per lens the folder that holds its panoramas (a `panoramas` product of scripts/panorama_stitching.jl:
  panorama_<candidate>.png for every column's candidate);
- `generator`: what the written files name as their generator (by default this file; the stage `figures` of
  scripts/panorama_figure.jl names itself).

The settings are required, the stage hands them from its config of record:
- `asset_dir`: the figure's name — its file, the folder of its panels and its caption's file (`[figure] asset_dir`);
- `order`: the lenses, the rows from the top (`[figure] order`);
- `panels`: per lens the name its panels' files begin with (`[lenses.<lens>] panel`);
- `labels`: per lens its name in two lines, `(first, second)` (`[lenses.<lens>] label`): turned at the left of its row at text
  width; in one column, and in the caption, the two joined by a space;
- `apertures`: per lens its aperture in the caption, LaTeX (`[lenses.<lens>] aperture`);
- `columns`: the columns from the left, each `(; panel, candidate, title)` — the end of its panels' file names, the panorama
  stage's candidate it shows and its title (`[figure] columns`); the caption is written for two: the frames as they are, then the
  frames with our learned vignetting divided out;
- `gain`, `gamma`: the display curve, the same on every panel (`[figure] gain`, `gamma`);
- `width`: the panels' width in pixels (`[figure] width_px`).
"""
function figure_panoramas(; panoramas::AbstractDict, out::AbstractString, generator::AbstractString = "experiments/src/paper_figures/panoramas.jl",
                          asset_dir::AbstractString, order, panels::AbstractDict, labels::AbstractDict, apertures::AbstractDict, columns,
                          gain::Real, gamma::Real, width::Integer)
    NAME = asset_dir; GEN = "generated by $generator; do not edit"; WP = Int(width)
    # pt: between the two columns; between the rows; the turned labels' column; under a line of text
    COLGAP, ROWGAP, LABELW, HEADGAP = 4, 3, 17, 2
    NARROW = "4.5in"                 # below this \linewidth there are no turned labels: each lens name is a line over its row
    (!isempty(order) && allunique(order)) || error("order: the lenses, each once")
    all(k -> haskey(panoramas, k) && haskey(panels, k) && haskey(labels, k) && haskey(apertures, k), order) ||
        error("figure_panoramas: a lens of $(join(order, ", ")) has no folder, no panel, no label or no aperture")
    length(columns) == 2 || error("columns: two — the frames as they are, and the frames with the learned vignetting divided out (the caption is written for them)")
    (gain > 0 && gamma > 0) || error("gain and gamma must be positive")
    name(k) = join(labels[k], " ")                               # the lens's name in one line
    gs = general(gain, 6); gms = general(gamma, 6)                # as Python's {:g} prints them
    table = panorama_display_table(gain, gamma)
    written = String[]
    mkpath(joinpath(out, NAME))

    rows = []        # per row: the lens key and its panels' file stems
    for k in order
        slug = panels[k]; sizes = Set{Tuple{Int, Int}}(); stems = String[]
        for c in columns
            f = "panorama_$(c.candidate).png"; p = joinpath(panoramas[k], f); isfile(p) || error("no $p")
            im = load_png(p); h, w = size(im)[1:2]; push!(sizes, (w, h))      # one panorama at a time: they are large
            H = round(Int, WP * h / w)
            png = joinpath(out, NAME, "$slug-$(c.panel).png")
            push!(written, save_png(png, pillow_resize_lanczos(map(v -> table[v+1], im), WP, H)))
            push!(written, image_panel(joinpath(out, NAME, "$slug-$(c.panel).tex"),
                "% $NAME/$slug-$(c.panel).tex — $GEN.\n% One panel: $(name(k)), $(c.title) — $f ($w x $h px) of the stack's panorama stage, " *
                "display curve gain $gs, gamma $gms, drawn at $WP x $H px.", NAME, "$slug-$(c.panel).png", WP, H))
            push!(stems, "$slug-$(c.panel)")
        end
        length(sizes) == 1 || error("$k: the two panoramas differ in size: $sizes")
        push!(rows, (k, stems))
    end

    # the composition: a tabular; at text width the lens names stand turned in a column at the left, in one column each lens
    # name is a line over its row
    inp(stem) = "\\input{\\rcfigdir/$NAME/$stem}"
    title(t) = "{\\scriptsize $t}"
    turned(two) = "\\makebox[$(LABELW)pt][l]{\\tikz[baseline=(n.center)]\\node[rotate=90,inner sep=0pt,align=center,font=\\scriptsize](n){$(two[1])\\\\$(two[2])};}"
    gap(pt) = "\\\\\\noalign{\\vskip $(pt)pt}"
    titles = join((title(c.title) for c in columns), " & ")
    wide = ["\\setlength{\\rcpanelwd}{\\dimexpr(\\linewidth-$(LABELW)pt-$(COLGAP)pt)/2\\relax}\\def\\rcpanelwidth{\\rcpanelwd}%",
            "\\begin{tabular}{@{}l@{}c@{\\hspace{$(COLGAP)pt}}c@{}}",
            "  & " * titles * " $(gap(HEADGAP))"]
    narrow = ["\\setlength{\\rcpanelwd}{\\dimexpr(\\linewidth-$(COLGAP)pt)/2\\relax}\\def\\rcpanelwidth{\\rcpanelwd}%",
              "\\begin{tabular}{@{}c@{\\hspace{$(COLGAP)pt}}c@{}}",
              "  " * titles * " $(gap(HEADGAP))"]
    for (i, (k, stems)) in enumerate(rows)
        after = i == length(rows) ? " \\\\" : " $(gap(ROWGAP))"
        push!(wide, "  $(turned(labels[k])) & " * join(inp.(stems), " & ") * after)
        push!(narrow, "  \\multicolumn{2}{@{}c@{}}{$(title(name(k)))} $(gap(HEADGAP))")
        push!(narrow, "  " * join(inp.(stems), " & ") * after)
    end
    push!(wide, "\\end{tabular}%"); push!(narrow, "\\end{tabular}%")
    push!(written, write_lines(joinpath(out, "$NAME.tex"), [
        "% $NAME.tex — $GEN.",
        "% The panoramas of the stack's own panorama stage: one row per lens, left the frames as they are, right the frames with our learned",
        "% vignetting divided out. Every panel is its own PGFPlots picture ($NAME/*.tex over its image); the column titles and the lens",
        "% names are LaTeX text in the host document's fonts. \\input it at text width (figure*): the lens names stand turned at the left.",
        "% In one column (\\linewidth below $NARROW) each lens name is a line over its row instead. It needs pgfplots (compat 1.18).",
        "% \\rcfigdir is the folder this file lies in, as the host document sees it (default src/fig).",
        "\\providecommand{\\rcfigdir}{src/fig}%",
        "\\begingroup",
        "\\ifdefined\\rcpanelwd\\else\\newlength\\rcpanelwd\\fi",
        "\\footnotesize\\setlength{\\tabcolsep}{0pt}\\renewcommand{\\arraystretch}{1}%",
        "\\ifdim\\linewidth<$NARROW\\relax", narrow..., "\\else", wide..., "\\fi", "\\endgroup"]))

    names = ["$(name(k)) at $(apertures[k])" for (k, _) in rows]
    push!(written, write_lines(joinpath(out, "$NAME-caption.tex"), [
        "Panoramas of one pure-rotation sweep per lens (" * (length(names) > 1 ? join(names[1:end-1], ", ") * " and " * names[end] : names[1]) * "), " *
        "composed by our stack's own panorama stage, which samples every pixel of the panorama through the calibrated camera, " *
        "without feature registration and without blending. " *
        "Left: the frames as they are. Right: the same frames with our learned vignetting divided out. " *
        "All panels are drawn with the same display curve (gain $gs, gamma $gms)."]))
    return written
end

FIGURES["panoramas"] = figure_panoramas
